-- ---------- 5) 物料主数据补再订货点 ROP_QTY（BR-4.5-14，design D5；032/033 守卫先例） ----------
SET @ddl = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE()
        AND TABLE_NAME = 'erp_mdm_item'
        AND COLUMN_NAME = 'ROP_QTY') = 0,
    'ALTER TABLE erp_mdm_item ADD COLUMN ROP_QTY DECIMAL(18,4) DEFAULT NULL COMMENT ''再订货点（0/NULL=不启用安全库存补货策略，BR-4.5-14）'' AFTER SAFETY_STOCK',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- ---------- 6) 物料主数据补最大库存 MAX_STOCK（FR-4.5-2-6 超库存提示，实施期补入） ----------
SET @ddl = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE()
        AND TABLE_NAME = 'erp_mdm_item'
        AND COLUMN_NAME = 'MAX_STOCK') = 0,
    'ALTER TABLE erp_mdm_item ADD COLUMN MAX_STOCK DECIMAL(18,4) DEFAULT NULL COMMENT ''最大库存（0/NULL=不启用超库存提示，FR-4.5-2-6）'' AFTER ROP_QTY',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
