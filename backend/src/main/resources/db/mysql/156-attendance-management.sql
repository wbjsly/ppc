-- ---------- 1. HR 班次库（独立于生产班次 erp_admin_shift） ----------
CREATE TABLE IF NOT EXISTS hr_shift (
    ID                 VARCHAR(32)   NOT NULL,
    SHIFT_NO           VARCHAR(16)   NOT NULL COMMENT '班次编码 SHIFT+4 位流水',
    NAME               VARCHAR(64)   NOT NULL COMMENT '班次名称',
    START_TIME         VARCHAR(8)    NOT NULL COMMENT '上班时间 HH:mm',
    END_TIME           VARCHAR(8)    NOT NULL COMMENT '下班时间 HH:mm（可跨天，夜班）',
    HOURS              DECIMAL(5,2)  NOT NULL COMMENT '工时（跨天按跨天计）',
    CROSS_DAY          CHAR(1)       NOT NULL DEFAULT '0' COMMENT '跨天班次 1=是',
    OVERTIME_ELIGIBLE  CHAR(1)       NOT NULL DEFAULT '1' COMMENT '是否计薪班次（可产生加班）',
    TOLERANCE_MIN      INT           NOT NULL DEFAULT 10 COMMENT '弹性容差分钟（迟到/早退宽限）',
    STATUS             VARCHAR(1)    NOT NULL DEFAULT '1' COMMENT '1 启用 / 0 停用',
    CREATE_BY          VARCHAR(64)   NULL,
    CREATE_DATE        DATETIME      NULL,
    UPDATE_BY          VARCHAR(64)   NULL,
    UPDATE_DATE        DATETIME      NULL,
    DEL_FLAG           CHAR(1)       NOT NULL DEFAULT '0',
    VER_NO             INT           NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_SHIFT_NO (SHIFT_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='HR 班次库（M10-3-1）';

-- ---------- 2. 排班日历（员工×日期×班次/休息，到人到天） ----------
CREATE TABLE IF NOT EXISTS hr_schedule (
    ID          VARCHAR(32)  NOT NULL,
    EMP_ID      VARCHAR(32)  NOT NULL COMMENT '员工（hr_employee.ID）',
    WORK_DATE   DATE         NOT NULL,
    SHIFT_ID    VARCHAR(32)  NULL COMMENT '班次（IS_REST=1 时为空）',
    IS_REST     CHAR(1)      NOT NULL DEFAULT '0' COMMENT '休息日 1=是',
    SOURCE      VARCHAR(16)  NOT NULL DEFAULT 'SINGLE' COMMENT 'SINGLE 单条 / BULK 部门批量 / COPY 复制上月',
    REMARK      VARCHAR(128) NULL,
    CREATE_BY   VARCHAR(64)  NULL,
    CREATE_DATE DATETIME     NULL,
    UPDATE_BY   VARCHAR(64)  NULL,
    UPDATE_DATE DATETIME     NULL,
    DEL_FLAG    CHAR(1)      NOT NULL DEFAULT '0',
    VER_NO      INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_HR_SCHEDULE_EMP_DATE (EMP_ID, WORK_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='排班日历（同人同日重排以最后一次为准，非 UK）';

