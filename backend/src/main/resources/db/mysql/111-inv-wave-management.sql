-- ---------- 1) 配送线路主数据（C-0-05 停用退役，不物理删除） ----------
CREATE TABLE IF NOT EXISTS erp_inv_route (
    ID VARCHAR(64) NOT NULL,
    ROUTE_CODE VARCHAR(32) NOT NULL COMMENT '线路编码',
    ROUTE_NAME VARCHAR(128) NOT NULL COMMENT '线路名称',
    -- ACTIVE 启用 / INACTIVE 停用（停用后不可被新发货单挂线，存量快照不受影响）
    STATUS VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT '状态（停用=退役语义）',
    REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_INV_ROUTE_CODE (ROUTE_CODE),
    KEY IDX_INV_ROUTE_STATUS (STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci
  COMMENT='配送线路主数据（4.8 波次聚类第一优先级键；wave-management 需求 配送线路主数据）';

-- ---------- 2) 客户挂默认线路（集团级：CUSTOMER_CODE/发货单客户编码来自集团，跨法人共享线路）
