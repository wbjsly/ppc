-- ---------- 3) 外协发料单（spec outsourcing-material-supply：甲供调拨至供应商保管） ----------
CREATE TABLE IF NOT EXISTS erp_mrp_os_material (
    ID VARCHAR(64) NOT NULL,
    OSM_NO VARCHAR(32) NOT NULL COMMENT '发料单号 OSM+yyyyMMdd+流水',
    DISPATCH_ID VARCHAR(64) NOT NULL COMMENT '外协派工单（OS_SUPPLY_TYPE=COMPANY_SUPPLY 前置校验）',
    DISPATCH_NO VARCHAR(64) NOT NULL,
    MO_NO VARCHAR(64) DEFAULT NULL COMMENT '工单号（冗余查询）',
    OP_SEQ INT DEFAULT NULL COMMENT '工序序号',
    SUPPLIER_CODE VARCHAR(64) NOT NULL COMMENT '收料供应商（随外协 WC 关联）',
    SUPPLIER_NAME VARCHAR(128) DEFAULT NULL,
    STATUS VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT/POSTED/RETURNED（发料过账/余料已退）',
    POST_BY VARCHAR(64) DEFAULT NULL,
    POST_DATE DATETIME DEFAULT NULL,
    RETURN_DATE DATETIME DEFAULT NULL COMMENT '余料退回完成时间',
    REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_MRP_OSM_NO (OSM_NO),
    KEY IDX_MRP_OSM_DISPATCH (DISPATCH_ID),
    KEY IDX_MRP_OSM_SUPPLIER (SUPPLIER_CODE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

