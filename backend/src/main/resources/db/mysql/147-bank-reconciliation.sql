-- add-bank-reconciliation：银行对账（M8-7，design D1/D7：对账单头表 + 处理留痕轻表 + M8-7 菜单 PERM）
-- 幂等：CREATE TABLE IF NOT EXISTS + UPDATE 守卫；逐笔流水复用 erp_fin_bank_receipt（不建行表）

-- ---------- 1. 银行对账单头表（design D1：账户×期间唯一，余额锚点+确认状态机） ----------
CREATE TABLE IF NOT EXISTS erp_fin_bank_statement (
    ID VARCHAR(64) NOT NULL,
    BANK_ACCOUNT_ID VARCHAR(64) NOT NULL COMMENT '银行账户（BR-4.6-34 按账户币种分别对账）',
    ACCOUNT_NAME VARCHAR(64) DEFAULT NULL,
    ACCOUNT_NO VARCHAR(32) DEFAULT NULL,
    CURRENCY VARCHAR(8) NOT NULL DEFAULT 'CNY' COMMENT '账户币种（冗余自账户）',
    PERIOD VARCHAR(6) NOT NULL COMMENT '对账期间 YYYYMM',
    STMT_NO VARCHAR(64) DEFAULT NULL COMMENT '银行对账单号（载明）',
    OPENING_BALANCE DECIMAL(18,2) NOT NULL DEFAULT 0.00 COMMENT '期初余额（对账单载明值）',
    CLOSING_BALANCE DECIMAL(18,2) NOT NULL COMMENT '期末余额（对账单载明值，权威锚点）',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT→CONFIRMED(出纳)→AUDITED(财务主管，FR-4.6-6-7/BR-4.6-36)',
    OVER_TOLERANCE VARCHAR(1) NOT NULL DEFAULT '0' COMMENT '1=差异率 > TOLERANCE_DEFAULT（C-0-02 进差异处理）',
    CONFIRM_BY VARCHAR(64) DEFAULT NULL,
    CONFIRM_AT DATETIME DEFAULT NULL,
    AUDIT_BY VARCHAR(64) DEFAULT NULL,
    AUDIT_AT DATETIME DEFAULT NULL,
    REVOKE_REASON VARCHAR(255) DEFAULT NULL COMMENT '撤销原因（AUDITED→DRAFT 留痕）',
    REVOKE_BY VARCHAR(64) DEFAULT NULL,
    REVOKE_AT DATETIME DEFAULT NULL,
    REMARK VARCHAR(512),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_BANK_STMT_ACCT_PERIOD (BANK_ACCOUNT_ID, PERIOD),
    KEY IDX_FIN_BANK_STMT_PERIOD (PERIOD, STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='银行对账单（M8-7-4 余额锚点，spec bank-reconciliation）';

-- ---------- 2. 差异处理留痕轻表（design D7：追加式记录，同一锚可多次追加） ----------
CREATE TABLE IF NOT EXISTS erp_fin_bank_reconcile_item (
    ID VARCHAR(64) NOT NULL,
    BANK_ACCOUNT_ID VARCHAR(64) NOT NULL,
    PERIOD VARCHAR(6) NOT NULL COMMENT '对账期间 YYYYMM',
    ITEM_TYPE VARCHAR(24) NOT NULL COMMENT '四类：ENT_RCPT_BANK_PEND ①企业已收银行未收 / ENT_PAY_BANK_PEND ②企业已付银行未付 / BANK_RCPT_ENT_PEND ③银行已收企业未收 / BANK_PAY_ENT_PEND ④银行已付企业未付',
    ANCHOR_TYPE VARCHAR(16) NOT NULL COMMENT 'RECEIPT 回单 / CASH_DOC 收付款单',
    ANCHOR_ID VARCHAR(64) NOT NULL COMMENT '回单 ID 或收付款单 ID',
    ANCHOR_NO VARCHAR(64) DEFAULT NULL,
    AMOUNT DECIMAL(18,2) NOT NULL,
    TRADE_DATE DATE DEFAULT NULL COMMENT '交易日期（账龄基准）',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'OPEN' COMMENT 'OPEN/PROCESSING/DONE/ESCALATED（升级主管，提示性）',
    HANDLING_NOTE VARCHAR(512) DEFAULT NULL COMMENT '处理备注',
    HANDLE_BY VARCHAR(64) DEFAULT NULL,
    HANDLE_AT DATETIME DEFAULT NULL,
    REMARK VARCHAR(512),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    KEY IDX_FIN_BANK_RCV_ITEM (BANK_ACCOUNT_ID, PERIOD, STATUS),
    KEY IDX_FIN_BANK_RCV_ANCHOR (ANCHOR_TYPE, ANCHOR_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='银行对账差异处理留痕（M8-7-3，spec bank-reconciliation）';

-- ---------- 3. M8-7 菜单 PERM 回填（与 M8-1~6 对齐：财务资产/财务经理/管理员） ----------
UPDATE erp_admin_menu SET PERM='ROLE_FIN_ASSET,ROLE_FIN_MGR,ROLE_ADMIN'
 WHERE ID IN ('M8-7','M8-7-1','M8-7-2','M8-7-3','M8-7-4') AND (PERM IS NULL OR PERM='');
