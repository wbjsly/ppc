-- ---------- 7) 建议行 MO_NO 回写列（design D1：D6 PMO 对接兑现——
--     PMO 入口建单时 UPDATE ... WHERE targetNo=? AND MO_NO IS NULL 幂等） ----------
SET @ddl = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE()
        AND TABLE_NAME = 'erp_mrp_suggestion'
        AND COLUMN_NAME = 'MO_NO') = 0,
    'ALTER TABLE erp_mrp_suggestion ADD COLUMN MO_NO VARCHAR(32) DEFAULT NULL COMMENT ''已关联工单号（PMO 转正后建单回写，NULL=未建）'' AFTER TARGET_NO',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
