-- ---------- 10. 数据回填（任务 1.2，全部幂等可重复执行） ----------
-- 10.1 历史单中标招标 → 中标子表补 1 行 100%（ID 确定性生成，INSERT IGNORE 幂等）
INSERT IGNORE INTO erp_proc_tender_award
    (ID, TENDER_ID, LINE_NO, SUPPLIER_ID, SUPPLIER_NAME, AWARD_PRICE, SHARE_PCT, CREATE_BY)
SELECT CONCAT('aw-', t.ID), t.ID, 1, t.AWARD_SUPPLIER_ID,
       (SELECT s.SUPPLIER_NAME FROM erp_mdm_supplier s WHERE s.ID = t.AWARD_SUPPLIER_ID),
       t.AWARD_PRICE, 100, 'system'
FROM erp_proc_tender t
WHERE t.AWARD_SUPPLIER_ID IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM erp_proc_tender_award a WHERE a.TENDER_ID = t.ID);

-- 10.2 既有协议行补已下单量默认值（新增列已有 DEFAULT，双保险回填 NULL）
UPDATE erp_proc_framework_agreement_line SET ORDERED_QTY = 0 WHERE ORDERED_QTY IS NULL;

-- 10.3 品类预算种子（2026 年度，每品类 100 万，保证超预算档可触发；INSERT IGNORE 幂等）
INSERT IGNORE INTO erp_proc_budget
    (ID, BUDGET_YEAR, CATEGORY_CODE, CATEGORY_NAME, BUDGET_AMT, CREATE_BY)
SELECT CONCAT('bud-2026-', c.CATEGORY_CODE), 2026, c.CATEGORY_CODE, c.CATEGORY_NAME,
       1000000.00, 'system'
FROM erp_mdm_item_category c
WHERE c.CATEGORY_CODE IS NOT NULL;
