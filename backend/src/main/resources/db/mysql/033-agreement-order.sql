-- ---------- 9. 价控校验日志（BR-4.2-19 完整校验日志） ----------
CREATE TABLE IF NOT EXISTS erp_proc_po_price_control (
    ID VARCHAR(64) NOT NULL,
    PO_ID VARCHAR(64),
    PO_NO VARCHAR(32),
    LINE_NO INT,
    ITEM_CODE VARCHAR(64),
    -- CONTRACT / HISTORY / BUDGET
    CHECK_LEVEL VARCHAR(16) NOT NULL,
    -- 基准值（协议价 / 历史均价 / 预算×阈值）
