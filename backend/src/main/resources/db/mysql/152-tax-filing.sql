-- ---------- 1. 申报单（增值税主表 + 所得税预缴共用，TAX_TYPE 区分） ----------
CREATE TABLE IF NOT EXISTS erp_fin_tax_return (
    ID VARCHAR(64) NOT NULL,
    RETURN_NO VARCHAR(32) NOT NULL COMMENT '申报单号 TRET+yyyyMM+流水（每税种每期一单，重申报走调整）',
    PERIOD VARCHAR(6) NOT NULL COMMENT '申报所属期 yyyyMM',
    TAX_TYPE VARCHAR(8) NOT NULL DEFAULT 'VAT' COMMENT 'VAT 增值税 / CIT 企业所得税预缴',
    -- 状态机：DRAFT→PENDING_APPROVAL→APPROVED→SUBMITTED→FILED→PAID；REJECTED/OVERDUE
    STATUS VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT '申报单状态机',
    -- 增值税汇总口径（BR-4.14-32 公式入参）
    OUTPUT_TAX DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '销项税额（按税率分档汇总，剔除作废/红冲净额）',
    INPUT_TAX DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '进项税额（已认证可抵扣）',
    TRANSFER_OUT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '进项税额转出',
    PREV_CREDIT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '上期期末留抵结转',
    PAYABLE_TAX DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '当期应纳税额（负值结转留抵，BR-4.14-32）',
    END_CREDIT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '期末留抵税额（应纳为负时结转下期）',
    -- 所得税口径
    CIT_BASE DECIMAL(18,2) DEFAULT NULL COMMENT '累计利润总额（总账取数）',
    CIT_ADJUST DECIMAL(18,2) DEFAULT NULL COMMENT '纳税调整项汇总（手工录入）',
    CIT_RATE DECIMAL(8,6) DEFAULT NULL COMMENT '适用税率（SysParam CIT_RATE 快照）',
    CIT_CUM_PAYABLE DECIMAL(18,2) DEFAULT NULL COMMENT '累计应纳税额',
    CIT_PREPAID DECIMAL(18,2) DEFAULT NULL COMMENT '年内已预缴',
    CIT_DUE DECIMAL(18,2) DEFAULT NULL COMMENT '本期应补退税额',
    -- 勾稽（C-4.14-04 / BR-4.14-30）
    RECON_STATUS VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/PASSED/BLOCKED',
    RECON_DIFF_TOTAL DECIMAL(18,2) DEFAULT NULL COMMENT '最近一次勾稽差异合计（阻断时>0）',
    -- 审批与锁定（FR-4.14-5-5：APPROVED 起锁定，修改走跨期调整）
    APPR_ID VARCHAR(64) COMMENT '审批实例 ID',
    LOCK_FLAG CHAR(1) NOT NULL DEFAULT '0' COMMENT '1=已锁定（审批通过起）',
    -- 缴款回执（FR-4.14-5-6 离线登记）
    SUBMIT_DATE DATE DEFAULT NULL COMMENT '提交税务机关日期',
    RECEIPT_NO VARCHAR(64) DEFAULT NULL COMMENT '电子税务局回执编号',
    FILE_DATE DATE DEFAULT NULL COMMENT '申报成功日期',
    PAY_DATE DATE DEFAULT NULL COMMENT '缴款日期',
    PAY_AMOUNT DECIMAL(18,2) DEFAULT NULL COMMENT '缴款金额',
    PAY_VOUCHER_NO VARCHAR(64) DEFAULT NULL COMMENT '缴款凭证号',
    -- 逾期事件单（滞纳金估算 + 升级）
    OVERDUE_FLAG CHAR(1) NOT NULL DEFAULT '0' COMMENT '1=逾期申报事件',
    OVERDUE_DAYS INT DEFAULT NULL COMMENT '滞纳天数',
    LATE_FEE DECIMAL(18,2) DEFAULT NULL COMMENT '估算滞纳金 = 滞纳税款 × 0.05% × 天数',
    FAULT_NOTE VARCHAR(500) DEFAULT NULL COMMENT '故障说明（系统/通道故障证据留痕）',
    ESCALATED_FLAG CHAR(1) NOT NULL DEFAULT '0' COMMENT '1=已升级财务经理',
    ADJUSTED_FLAG CHAR(1) NOT NULL DEFAULT '0' COMMENT '1=存在跨期调整记录',
    REMARK VARCHAR(500),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_TRET_NO (RETURN_NO),
    KEY IDX_FIN_TRET_PERIOD (PERIOD, TAX_TYPE),
    KEY IDX_FIN_TRET_STATUS (STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='纳税申报单（M9-5-1/2，spec tax-filing）';

-- ---------- 2. 申报栏次明细（BR-4.14-30 栏次级差异的结构基础） ----------
CREATE TABLE IF NOT EXISTS erp_fin_tax_return_line (
    ID VARCHAR(64) NOT NULL,
    RETURN_ID VARCHAR(64) NOT NULL,
    LINE_CODE VARCHAR(64) NOT NULL COMMENT '栏次编码（命名空间化：主表-销项税额 / 附表1-13% / 附表2-已认证 / 附加税-城建）',
    LINE_NAME VARCHAR(128) NOT NULL COMMENT '栏次名称',
    AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '栏次金额',
    SOURCE_DESC VARCHAR(255) DEFAULT NULL COMMENT '来源描述（可追溯到台账明细）',
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    KEY IDX_FIN_TRETLINE_RET (RETURN_ID),
    KEY IDX_FIN_TRETLINE_CODE (RETURN_ID, LINE_CODE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='申报栏次明细（tax-filing design D1）';

-- ---------- 3. 跨期调整单（BR-4.14-31 快照留痕） ----------
