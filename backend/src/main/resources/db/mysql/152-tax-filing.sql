    MTD_REFUND_TOTAL DECIMAL(18,2) DEFAULT NULL COMMENT '免抵退税额',
    MTD_REFUND_DUE DECIMAL(18,2) DEFAULT NULL COMMENT '当期应退税额',
    MTD_EXEMPT_TAX DECIMAL(18,2) DEFAULT NULL COMMENT '当期免抵税额',
    MTD_END_CREDIT DECIMAL(18,2) DEFAULT NULL COMMENT '期末留抵税额',
    VAT_RETURN_ID VARCHAR(64) DEFAULT NULL COMMENT '勾稽锚：同期增值税申报单',
    REMARK VARCHAR(500),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_RFA_NO (APPLY_NO),
    KEY IDX_FIN_RFA_STATUS (STATUS),
    KEY IDX_FIN_RFA_PERIOD (PERIOD)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='出口退税申报单（spec export-tax-refund）';

