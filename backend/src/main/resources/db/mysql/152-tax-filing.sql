-- ---------- 4. 留抵退税申请（BR-4.14-33 / S-4.14-15） ----------
CREATE TABLE IF NOT EXISTS erp_fin_tax_refund_apply (
    ID VARCHAR(64) NOT NULL,
    APPLY_NO VARCHAR(32) NOT NULL COMMENT '申请单号 RVAP+yyyyMMdd+流水',
    PERIOD VARCHAR(6) NOT NULL COMMENT '申请所属期（期末留抵所在期）',
    CREDIT_LEVEL VARCHAR(8) NOT NULL COMMENT '纳税信用等级 A/B/M/C/D',
    INCR_CREDIT DECIMAL(18,2) NOT NULL COMMENT '增量留抵税额',
    CONSTITUTION_RATIO DECIMAL(8,6) NOT NULL COMMENT '进项构成比例（0~1）',
    REFUND_RATIO DECIMAL(8,6) NOT NULL COMMENT '退还比例（SysParam LDTI_REFUND_RATIO 快照）',
    MONTH6_INCR DECIMAL(18,2) NOT NULL COMMENT '第 6 个月增量留抵税额',
    SIX_MONTH_JSON LONGTEXT COMMENT '申请前连续 6 个月增量留抵快照（条件②③校验依据）',
    ALLOWED_REFUND DECIMAL(18,2) DEFAULT NULL COMMENT '允许退还 = 增量留抵 × 构成比例 × 退还比例',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'DRAFT'
        COMMENT 'DRAFT/PENDING_APPROVAL/ACCEPTED/RETURNED/APPROVED/PAID/REJECTED',
    APPR_ID VARCHAR(64),
    RETURN_REASON VARCHAR(500) DEFAULT NULL COMMENT '退回原因',
    CORRECTIONS_JSON LONGTEXT COMMENT '结构化补正任务清单（原因码/涉及票号/补正期限）',
    APPROVED_AMOUNT DECIMAL(18,2) DEFAULT NULL COMMENT '核准退税额',
    RECEIVED_AMOUNT DECIMAL(18,2) DEFAULT NULL COMMENT '到账金额',
    RECEIVED_DATE DATE DEFAULT NULL,
    VOUCHER_ID VARCHAR(64) COMMENT '收款凭证（一致核销时生成）',
    RECONCILE_TASK_ID VARCHAR(64) COMMENT '差异挂账核查任务锚',
    REMARK VARCHAR(500),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_RVAP_NO (APPLY_NO),
    KEY IDX_FIN_RVAP_PERIOD (PERIOD),
    KEY IDX_FIN_RVAP_STATUS (STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='增值税留抵退税申请（tax-filing design D1）';

-- ---------- 5. 出口一票一档（FR-4.14-7-1，离线手工登记代理口径） ----------
CREATE TABLE IF NOT EXISTS erp_fin_export_deal (
    ID VARCHAR(64) NOT NULL,
    DEAL_NO VARCHAR(32) NOT NULL COMMENT '档案号 EXP+yyyyMMdd+流水（一票一档）',
    CUSTOMER_ID VARCHAR(64) DEFAULT NULL,
    CUSTOMER_NAME VARCHAR(128) DEFAULT NULL,
    INVOICE_NO VARCHAR(64) NOT NULL COMMENT '出口发票号',
    DECL_NO VARCHAR(64) NOT NULL COMMENT '报关单号',
    DECL_DATE DATE NOT NULL COMMENT '报关出口日期（申报截止/预警起算）',
    TRADE_TERM VARCHAR(8) NOT NULL DEFAULT 'FOB' COMMENT 'FOB/CIF/CFR',
    CURRENCY VARCHAR(8) NOT NULL DEFAULT 'USD',
    FX_RATE DECIMAL(18,6) DEFAULT NULL COMMENT '折算汇率（出口当月 1 日口径，登记时录入）',
    GROSS_AMOUNT DECIMAL(18,2) NOT NULL COMMENT '成交价（币别原币）',
    FREIGHT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '运费（CIF/CFR 扣减项）',
    INSURANCE DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '保险费',
    COMMISSION DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '佣金',
    FOB_CNY DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT 'FOB 折算人民币（BR-4.14-41）',
    ITEM_CATEGORY VARCHAR(64) DEFAULT NULL COMMENT '商品大类（退税率 SysParam 键）',
    REFUND_RATE DECIMAL(8,6) DEFAULT NULL COMMENT '退税率快照（报关日配置）',
    REFUND_TAX DECIMAL(18,2) DEFAULT NULL COMMENT '应退税额 = FOB_CNY × 退税率',
    DOC_DECL CHAR(1) NOT NULL DEFAULT '0' COMMENT '报关单收齐',
    DOC_INVOICE CHAR(1) NOT NULL DEFAULT '0' COMMENT '出口发票收齐',
    DOC_RECEIPT CHAR(1) NOT NULL DEFAULT '0' COMMENT '收汇凭证收齐',
    DOC_AGENT CHAR(1) DEFAULT NULL COMMENT '代理出口证明（委托出口时必收，NULL=非委托）',
    RECEIPT_DATE DATE DEFAULT NULL COMMENT '收汇日期（临期 30 天预警）',
    MISMATCH_FLAG CHAR(1) NOT NULL DEFAULT '0' COMMENT '1=报关单与出口发票不一致（L4 预警待核实）',
    MISMATCH_NOTE VARCHAR(255) DEFAULT NULL,
    EXPIRE_DATE DATE DEFAULT NULL COMMENT '申报截止日 = 报关次年 4 月申报期截止（C-4.14-13 起算）',
    REFUND_APPLY_NO VARCHAR(32) DEFAULT NULL COMMENT '所属退税申报单锚（多对一）',
    REMARK VARCHAR(500),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_EXPDEAL_NO (DEAL_NO),
    KEY IDX_FIN_EXPDEAL_APPLY (REFUND_APPLY_NO),
    KEY IDX_FIN_EXPDEAL_DECL (DECL_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='出口业务一票一档（spec export-tax-refund）';

-- ---------- 6. 出口退税申报单（多票聚合 + 状态机 + 免抵退勾稽） ----------
