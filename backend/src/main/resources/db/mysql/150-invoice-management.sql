-- ---------- 1. 进项发票台账（D1 全生命周期状态机：登记→匹配→查验→认证→凭证锚） ----------
CREATE TABLE IF NOT EXISTS erp_fin_input_invoice (
    ID VARCHAR(64) NOT NULL,
    INVOICE_NO VARCHAR(32) NOT NULL COMMENT '发票号码（唯一）',
    SUPPLIER_ID VARCHAR(64) NOT NULL,
    SUPPLIER_NAME VARCHAR(128),
    INVOICE_DATE DATE NOT NULL COMMENT '开票日（认证期限起算，C-4.14-07）',
    AMOUNT DECIMAL(18,2) NOT NULL COMMENT '价税合计',
    TAX_AMOUNT DECIMAL(18,2) NOT NULL COMMENT '税额',
    PO_ID VARCHAR(64) NOT NULL COMMENT '关联 PO（三单匹配锚，登记必填）',
    PO_NO VARCHAR(32) NOT NULL,
    MATCH_STATUS VARCHAR(16) NOT NULL DEFAULT 'MATCHED' COMMENT 'MATCHED/DIFF（超差红标阻断认证）',
    QTY_DIFF_RATE DECIMAL(10,6) COMMENT '数量差异率（有发票行明细时）',
    AMOUNT_DIFF_RATE DECIMAL(10,6) COMMENT '金额差异率 vs PO 未开票余额',
    MATCH_DETAIL VARCHAR(512) COMMENT '匹配快照（差异额/比例/说明）',
    INSPECT_METHOD VARCHAR(32) COMMENT '查验方式（登记留痕位：MANUAL/PLATFORM）',
    INSPECT_RESULT VARCHAR(16) COMMENT '查验结果 PASS/FAIL',
    INSPECT_AT DATETIME COMMENT '查验时间',
    CERT_STATUS VARCHAR(16) NOT NULL DEFAULT 'PENDING_CERT' COMMENT 'PENDING_CERT/CERTIFIED/NOT_DEDUCTIBLE',
    CERT_DATE DATE COMMENT '认证日期（外部勾选后登记）',
    CERT_PERIOD VARCHAR(6) COMMENT '认证所属期 YYYYMM（=认证日锁定，C-4.14-11 不得跨期）',
    DEDUCTIBLE CHAR(1) NOT NULL DEFAULT 'Y' COMMENT 'Y=可抵扣/N=超期自动不可抵扣（C-4.14-07）',
    CERT_NOTE VARCHAR(255) COMMENT '认证备注（超期转成本提示留痕）',
    VOUCHER_ID VARCHAR(64) COMMENT '进项凭证（批量生成 DRAFT；TAXIN 锚=发票号）',
    REMARK VARCHAR(255),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_TAXIN_NO (INVOICE_NO),
    KEY IDX_FIN_TAXIN_CERT (CERT_PERIOD, CERT_STATUS),
    KEY IDX_FIN_TAXIN_PO (PO_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='进项发票台账（M9-2-2，spec invoice-management）';

-- ---------- 2. 数电授信额度（D5 一期一行） ----------
CREATE TABLE IF NOT EXISTS erp_fin_digital_quota (
    ID VARCHAR(64) NOT NULL,
    PERIOD VARCHAR(6) NOT NULL COMMENT '额度期间 YYYYMM',
    TOTAL_LIMIT DECIMAL(18,2) NOT NULL COMMENT '核定总额度（税务专员按税局核定登记）',
    USED_AMT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '已用（每次 ISSUED 累加扣减）',
    REMARK VARCHAR(255),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_DQ_PERIOD (PERIOD)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='数电票授信额度台账（M9-2-3，BR-4.14-36）';

-- ---------- 3. 数电开票请求队列（D5：幂等键唯一+按序补开+超限拆分） ----------
CREATE TABLE IF NOT EXISTS erp_decoded_request (
    ID VARCHAR(64) NOT NULL,
    REQ_NO VARCHAR(32) NOT NULL COMMENT '请求号 DSR+yyyyMMdd+流水',
    CLIENT_NAME VARCHAR(128) NOT NULL COMMENT '客户名称',
    AMOUNT DECIMAL(18,2) NOT NULL COMMENT '请求金额（价税合计）',
    SO_NO VARCHAR(32) COMMENT '关联销售订单号',
    SHIP_NO VARCHAR(32) COMMENT '关联出库单号',
    IDEMPOTENT_KEY VARCHAR(96) NOT NULL COMMENT '幂等键 SO+出库+行（BR-4.14-37 重复 422）',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/ISSUED',
    INVOICE_NOS VARCHAR(255) COMMENT '补开后发票号（拆分时逗号串）',
    SPLIT_COUNT INT DEFAULT 1 COMMENT '拆分张数（BR-4.14-15 行降序）',
    ISSUE_AT DATETIME COMMENT '补开时间',
    ARCHIVE_XML VARCHAR(255) COMMENT 'XML 源文件名（归档登记位，上传 OOS）',
    ARCHIVE_PDF VARCHAR(255) COMMENT '版式文件名（PDF/OFD 登记位）',
    REMARK VARCHAR(255),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_DSR_NO (REQ_NO),
    UNIQUE KEY UK_FIN_DSR_IDEM (IDEMPOTENT_KEY),
    KEY IDX_FIN_DSR_STATUS (STATUS, CREATE_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='数电开票请求队列（M9-2-3，spec invoice-management）';

-- ---------- 4. 发票交付记录（D6 双路：数电自动 PENDING + 销项手工登记） ----------
CREATE TABLE IF NOT EXISTS erp_fin_invoice_delivery (
    ID VARCHAR(64) NOT NULL,
    INVOICE_NO VARCHAR(32) NOT NULL COMMENT '发票号（销项 sales_invoice 或数电 DSI）',
    SOURCE VARCHAR(16) NOT NULL COMMENT 'SOURCE=DIGITAL/SALES',
    SOURCE_ID VARCHAR(64) COMMENT '请求 ID 或 sales_invoice ID',
    METHOD VARCHAR(16) COMMENT 'EMAIL/SMS/LINK/MAIL/PICKUP（数电自动行待选）',
    CONTACT VARCHAR(255) COMMENT '收件人/邮箱/地址',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/SENT/FAILED',
    SENT_AT DATETIME COMMENT '交付时间',
    RETRY_COUNT INT NOT NULL DEFAULT 0 COMMENT '重发次数（上限 SysParam DELIVERY_MAX_RETRY）',
    REMARK VARCHAR(255),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    KEY IDX_FIN_DELIV_INVOICE (INVOICE_NO),
    KEY IDX_FIN_DELIV_STATUS (STATUS, CREATE_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='发票交付记录（M9-2-4，FR-4.14-2-4）';

