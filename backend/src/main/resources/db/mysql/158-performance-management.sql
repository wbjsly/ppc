-- ---------- 1. 绩效方案（周期+等级定义+系数映射） ----------
CREATE TABLE IF NOT EXISTS hr_perf_plan (
    ID             VARCHAR(32) NOT NULL,
    PLAN_NO        VARCHAR(32) NOT NULL COMMENT '方案编码 PL+yyyyMMdd-序号',
    NAME           VARCHAR(100) NOT NULL COMMENT '方案名称',
    DEPT_ID        VARCHAR(32) NULL COMMENT '适用部门（空=全公司）',
    PERIOD_TYPE    VARCHAR(10) NOT NULL COMMENT 'YEAR/HALF/MONTH',
    PERIOD         VARCHAR(10) NOT NULL COMMENT '周期标识 如 2026H2/2026-10',
    GRADE_JSON     VARCHAR(1000) NOT NULL COMMENT '等级定义 JSON [{grade,coef,minScore,maxScore}]',
    STATUS         VARCHAR(16) NOT NULL COMMENT 'DRAFT/ACTIVE/CLOSED/VOID',
    CLOSE_AT       DATETIME NULL,
    UK_PERM        VARCHAR(64) NOT NULL COMMENT '同周期同部门唯一 UK（DEPT_ID 空用 ALL）',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_PERF_PLAN_NO (PLAN_NO),
    UNIQUE KEY UK_HR_PERF_PLAN_UK (UK_PERM),
    KEY IDX_HR_PERF_PLAN_PERIOD (PERIOD)
) COMMENT='绩效方案';

-- ---------- 2. 绩效评分（员工×周期，DRAFT→SUBMITTED） ----------
CREATE TABLE IF NOT EXISTS hr_perf_score (
    ID             VARCHAR(32) NOT NULL,
    PLAN_ID        VARCHAR(32) NOT NULL,
    PERIOD         VARCHAR(10) NOT NULL,
    EMP_ID         VARCHAR(32) NOT NULL,
    EMP_NO         VARCHAR(32) NULL,
    EMP_NAME       VARCHAR(64) NULL,
    DEPT_ID        VARCHAR(32) NULL,
    SCORE          DECIMAL(6,2) NULL COMMENT '分值',
    GRADE          VARCHAR(4) NOT NULL COMMENT 'A/B/C/D',
    COEF           DECIMAL(6,3) NOT NULL COMMENT '等级系数快照',
    COMMENT_TEXT   VARCHAR(500) NULL,
    STATUS         VARCHAR(16) NOT NULL COMMENT 'DRAFT/SUBMITTED/CALIBRATING/CALIBRATED/CONFIRMED',
    SUBMIT_AT      DATETIME NULL,
    CONFIRM_AT     DATETIME NULL,
    CONFIRM_BY     VARCHAR(64) NULL,
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_PERF_SCORE (PLAN_ID, EMP_ID),
    KEY IDX_HR_PERF_SCORE_PERIOD (PERIOD, STATUS)
) COMMENT='绩效评分';

-- ---------- 3. 校准日志（调整前后等级/原因/操作人，只增不改） ----------
CREATE TABLE IF NOT EXISTS hr_perf_calibrate_log (
    ID             VARCHAR(32) NOT NULL,
    SCORE_ID       VARCHAR(32) NOT NULL,
    PERIOD         VARCHAR(10) NOT NULL,
    ACTION         VARCHAR(20) NOT NULL COMMENT 'SUBMIT/CALIBRATE/ADJUST/REJECT/CONFIRM',
    FROM_GRADE     VARCHAR(4) NULL,
    TO_GRADE       VARCHAR(4) NULL,
    REASON         VARCHAR(500) NULL,
    OPERATOR       VARCHAR(64) NOT NULL,
    OP_AT          DATETIME NOT NULL,
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_HR_PERF_LOG_SCORE (SCORE_ID)
) COMMENT='绩效校准日志';

-- ---------- 4. 绩效结果快照（CONFIRMED 后不可改，薪酬取数来源） ----------
CREATE TABLE IF NOT EXISTS hr_perf_result (
    ID             VARCHAR(32) NOT NULL,
    PERIOD         VARCHAR(10) NOT NULL,
    EMP_ID         VARCHAR(32) NOT NULL,
    EMP_NO         VARCHAR(32) NULL,
    EMP_NAME       VARCHAR(64) NULL,
    DEPT_ID        VARCHAR(32) NULL,
    GRADE          VARCHAR(4) NOT NULL,
    COEF           DECIMAL(6,3) NOT NULL,
    SCORE_ID       VARCHAR(32) NOT NULL,
    CONFIRM_BY     VARCHAR(64) NOT NULL,
    CONFIRM_AT     DATETIME NOT NULL,
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_PERF_RESULT (PERIOD, EMP_ID),
    KEY IDX_HR_PERF_RESULT_DEPT (DEPT_ID)
) COMMENT='绩效结果快照';

