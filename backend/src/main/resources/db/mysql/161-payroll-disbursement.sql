-- ---------- 1. 代发文件（已审批 PayrollRun → CSV；重复生成须作废旧文件） ----------
CREATE TABLE IF NOT EXISTS hr_pay_disbursement (
    ID             VARCHAR(32) NOT NULL,
    FILE_NO        VARCHAR(32) NOT NULL COMMENT 'DF+yyyyMMdd-序号',
    RUN_ID         VARCHAR(32) NOT NULL COMMENT 'PayrollRun 批次',
    PERIOD         VARCHAR(6) NOT NULL,
    LINE_COUNT     INT NOT NULL,
    TOTAL_AMOUNT   DECIMAL(14,2) NOT NULL COMMENT '实发合计（须=批次实发）',
    FORMAT         VARCHAR(20) NOT NULL DEFAULT 'CSV',
    CONTENT        LONGTEXT NULL COMMENT '文件内容（CSV 文本，网银推送留桩=下载）',
    STATUS         VARCHAR(16) NOT NULL COMMENT 'ACTIVE/VOID',
    VOID_REASON    VARCHAR(200) NULL,
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_PAY_DISB (FILE_NO),
    KEY IDX_HR_PAY_DISB_RUN (RUN_ID, STATUS)
) COMMENT='银行代发文件（网银推送留桩，本期下载）';

-- ---------- 2. 发放执行登记（出纳手工登记；PAID/PARTIAL） ----------
CREATE TABLE IF NOT EXISTS hr_pay_execution (
    ID             VARCHAR(32) NOT NULL,
    RUN_ID         VARCHAR(32) NOT NULL,
    DISB_ID        VARCHAR(32) NOT NULL,
    PERIOD         VARCHAR(6) NOT NULL,
    PAY_DATE       DATE NOT NULL COMMENT '付款日期',
    PAY_ACCOUNT    VARCHAR(100) NULL COMMENT '付款账户',
    PAID_TOTAL     DECIMAL(14,2) NOT NULL COMMENT '实付合计（须=文件合计）',
    BANK_SERIAL    VARCHAR(100) NULL COMMENT '网银流水号',
    SUCCESS_COUNT  INT NOT NULL,
    FAIL_COUNT     INT NOT NULL DEFAULT 0,
    FAIL_DETAIL    VARCHAR(1000) NULL COMMENT '失败笔清单（员工/原因）',
    STATUS         VARCHAR(16) NOT NULL COMMENT 'PAID/PARTIAL',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_HR_PAY_EXEC_RUN (RUN_ID)
) COMMENT='发放执行登记（网银接口留桩）';

-- ---------- 3. 银行回单（手工登记/上传；自动获取留桩） ----------
CREATE TABLE IF NOT EXISTS hr_pay_receipt (
    ID             VARCHAR(32) NOT NULL,
    RECEIPT_NO     VARCHAR(64) NOT NULL COMMENT '回单号',
    RUN_ID         VARCHAR(32) NULL,
    DISB_ID        VARCHAR(32) NULL,
    RECEIPT_DATE   DATE NOT NULL,
    AMOUNT         DECIMAL(14,2) NOT NULL,
    SUMMARY        VARCHAR(200) NULL,
    MATCH_STATUS   VARCHAR(16) NOT NULL DEFAULT 'UNMATCHED' COMMENT 'UNMATCHED/MATCHED',
    MATCH_ITEM_ID  VARCHAR(32) NULL COMMENT '匹配到的代发明细行',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_PAY_RECEIPT (RECEIPT_NO),
    KEY IDX_HR_PAY_RECEIPT_RUN (RUN_ID, MATCH_STATUS)
) COMMENT='银行回单（逐笔匹配对账）';

-- ---------- 4. 发放差异处理（退汇重发/下月补差/手工发放；5 工作日时限；金额调整 L2） ----------
CREATE TABLE IF NOT EXISTS hr_pay_diff (
    ID             VARCHAR(32) NOT NULL,
    DIFF_NO        VARCHAR(32) NOT NULL,
    RUN_ID         VARCHAR(32) NOT NULL,
    PERIOD         VARCHAR(6) NOT NULL,
    EMP_ID         VARCHAR(32) NOT NULL,
    DIFF_TYPE      VARCHAR(20) NOT NULL COMMENT 'RETURNED 退汇/AMOUNT_MISMATCH 金额不一致/UNMATCHED 未匹配/FAILED 付款失败',
    EXPECT_AMOUNT  DECIMAL(12,2) NOT NULL,
    ACTUAL_AMOUNT  DECIMAL(12,2) NULL,
    RESOLVE_PLAN   VARCHAR(20) NULL COMMENT 'RESEND 退汇重发/NEXT_MONTH 下月补差/MANUAL 手工发放',
    RESOLVE_NOTE   VARCHAR(500) NULL,
    STATUS         VARCHAR(16) NOT NULL COMMENT 'OPEN/RESOLVED/CLOSED',
    DEADLINE       DATE NOT NULL COMMENT '5 工作日处理时限',
    APPR_BY        VARCHAR(64) NULL,
    APPR_AT        DATETIME NULL,
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_PAY_DIFF (DIFF_NO),
    KEY IDX_HR_PAY_DIFF_RUN (RUN_ID, STATUS)
) COMMENT='薪酬发放差异处理单';

