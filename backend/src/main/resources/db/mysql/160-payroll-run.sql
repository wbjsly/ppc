-- ---------- 3. 薪资核算与 PayrollRun ----------
-- 3.1 补扣项（部门/HR 申报，核算期内可改，批次生成后锁）
CREATE TABLE IF NOT EXISTS hr_pay_adjustment (
    ID             VARCHAR(32) NOT NULL,
    PERIOD         VARCHAR(6) NOT NULL COMMENT '核算期 yyyyMM',
    EMP_ID         VARCHAR(32) NOT NULL,
    ITEM_TYPE      VARCHAR(20) NOT NULL COMMENT 'MEAL_ALLOW/TRANSPORT_ALLOW/ATTEND_BONUS/LATE_FINE/OTHER',
    AMOUNT         DECIMAL(12,2) NOT NULL COMMENT '正=补贴 负=扣款',
    REASON         VARCHAR(200) NULL,
    LOCKED         CHAR(1) NOT NULL DEFAULT '0' COMMENT '1=随批次锁定',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_HR_PAY_ADJ (PERIOD, EMP_ID)
) COMMENT='薪酬补扣项（内嵌 10.5.3 录入）';

-- 3.2 PayrollRun 批次（PERIOD 唯一非作废；生成后明细冻结）
CREATE TABLE IF NOT EXISTS hr_payroll_run (
    ID             VARCHAR(32) NOT NULL,
    RUN_NO         VARCHAR(32) NOT NULL COMMENT 'PR+yyyyMMdd-序号',
    PERIOD         VARCHAR(6) NOT NULL COMMENT '核算期 yyyyMM',
    EMP_COUNT      INT NOT NULL,
    GROSS_TOTAL    DECIMAL(14,2) NOT NULL COMMENT '应发合计',
    DEDUCT_TOTAL   DECIMAL(14,2) NOT NULL COMMENT '扣款合计（社保个人+公积金个人+个税+其他）',
    NET_TOTAL      DECIMAL(14,2) NOT NULL COMMENT '实发合计',
    STATUS         VARCHAR(20) NOT NULL COMMENT 'DRAFT/SUBMITTING/APPROVED/REJECTED/VOID/PAID/PARTIAL/RECONCILED/ARCHIVED',
    VOID_REASON    VARCHAR(200) NULL,
    SUBMIT_AT      DATETIME NULL,
    APPROVE_AT     DATETIME NULL,
    APPROVE_BY     VARCHAR(64) NULL,
    APPROVE_OPINION VARCHAR(500) NULL,
    PARENT_RUN_ID  VARCHAR(32) NULL COMMENT '更正单关联原批次',
    RUN_TYPE       VARCHAR(10) NOT NULL DEFAULT 'NORMAL' COMMENT 'NORMAL/CORRECTION',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_PAYROLL_RUN_NO (RUN_NO),
    UNIQUE KEY UK_HR_PAYROLL_RUN_PERIOD (PERIOD, RUN_TYPE, PARENT_RUN_ID),
    KEY IDX_HR_PAYROLL_RUN_STATUS (STATUS)
) COMMENT='PayrollRun 批次';

-- 3.3 明细快照（生成时落库冻结；含全部分项）
CREATE TABLE IF NOT EXISTS hr_payroll_run_item (
    ID             VARCHAR(32) NOT NULL,
    RUN_ID         VARCHAR(32) NOT NULL,
    PERIOD         VARCHAR(6) NOT NULL,
    EMP_ID         VARCHAR(32) NOT NULL,
    EMP_NO         VARCHAR(32) NULL,
    EMP_NAME       VARCHAR(64) NULL,
    DEPT_ID        VARCHAR(32) NULL,
    COST_CENTER    VARCHAR(50) NULL,
    BASE_SALARY    DECIMAL(12,2) NOT NULL COMMENT '基本工资（出勤折算后）',
    PERF_AMOUNT    DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT '绩效工资',
    PERF_GRADE     VARCHAR(4) NULL,
    PERF_COEF      DECIMAL(6,3) NULL,
    PERF_NOTE      VARCHAR(50) NULL COMMENT '如 无绩效结果',
    ALLOWANCE      DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT '补贴合计（补扣项正向）',
    OVERTIME_WAGE  DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT '加班工资（取固化金额）',
    GROSS          DECIMAL(12,2) NOT NULL COMMENT '应发',
    SOCIAL_EE      DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT '社保个人',
    PROVIDENT_EE   DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT '公积金个人',
    IIT            DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT '个税',
    OTHER_DEDUCT   DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT '其他扣款（罚款+请假日工资扣减）',
    LEAVE_DEDUCT   DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT '请假日工资扣减（单列供汇总）',
    NET            DECIMAL(12,2) NOT NULL COMMENT '实发',
    NEG_FLAG       CHAR(1) NOT NULL DEFAULT '0' COMMENT '1=实发负数 L1 异常',
    VOLATILE_FLAG  CHAR(1) NOT NULL DEFAULT '0' COMMENT '1=环比>20% 待确认',
    HOLD_FLAG      CHAR(1) NOT NULL DEFAULT '0' COMMENT '1=考勤挂起未纳入（C-4.7-01，仅标注不生成 item 时用备注）',
    STATUS         VARCHAR(20) NOT NULL DEFAULT 'NORMAL' COMMENT 'NORMAL/NEGATIVE/VOLATILE/HOLD',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_PAYROLL_ITEM (RUN_ID, EMP_ID),
    KEY IDX_HR_PAYROLL_ITEM_PERIOD (PERIOD, EMP_ID)
) COMMENT='PayrollRun 明细快照';

-- 3.4 薪酬更正申请（L2 审批 → 更正批次关联原批次）
CREATE TABLE IF NOT EXISTS hr_pay_correction (
    ID             VARCHAR(32) NOT NULL,
    CORR_NO        VARCHAR(32) NOT NULL,
    PERIOD         VARCHAR(6) NOT NULL,
    RUN_ID         VARCHAR(32) NOT NULL COMMENT '原批次',
    EMP_ID         VARCHAR(32) NOT NULL,
    ADJUST_ITEM    VARCHAR(40) NOT NULL COMMENT '调整项（如 OVERTIME_WAGE/IIT）',
    ADJUST_AMOUNT  DECIMAL(12,2) NOT NULL COMMENT '正/负调整',
    REASON         VARCHAR(500) NOT NULL,
    STATUS         VARCHAR(20) NOT NULL COMMENT 'SUBMITTED/APPROVED/REJECTED/POSTED',
    APPR_BY        VARCHAR(64) NULL,
    APPR_AT        DATETIME NULL,
    APPR_OPINION   VARCHAR(500) NULL,
    CORRECTION_RUN_ID VARCHAR(32) NULL COMMENT '生成的更正批次',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_PAY_CORR (CORR_NO),
    KEY IDX_HR_PAY_CORR_RUN (RUN_ID)
) COMMENT='薪酬更正申请（BR-4.7-13 L2）';

-- 3.5 电子工资条（审批过生成推送；确认/异议留痕）
CREATE TABLE IF NOT EXISTS hr_payslip (
    ID             VARCHAR(32) NOT NULL,
    RUN_ID         VARCHAR(32) NOT NULL,
    ITEM_ID        VARCHAR(32) NOT NULL,
    PERIOD         VARCHAR(6) NOT NULL,
    EMP_ID         VARCHAR(32) NOT NULL,
    DETAIL_JSON    TEXT NOT NULL COMMENT '工资条快照 JSON（应发/扣款分项）',
    CONFIRMED_AT   DATETIME NULL COMMENT '员工确认（非强制）',
    DISPUTE_CONTENT VARCHAR(500) NULL,
    DISPUTE_AT     DATETIME NULL,
    REPLY_CONTENT  VARCHAR(500) NULL,
    REPLY_AT       DATETIME NULL,
    REPLY_BY       VARCHAR(64) NULL,
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_PAYSLIP (RUN_ID, EMP_ID),
    KEY IDX_HR_PAYSLIP_EMP (EMP_ID, PERIOD)
) COMMENT='电子工资条';

-- 3.6 薪酬审计日志（BR-4.7-15 L5 只插不改）
CREATE TABLE IF NOT EXISTS pay_audit_log (
    ID             VARCHAR(32) NOT NULL,
    ACTOR          VARCHAR(64) NOT NULL,
    ACTION         VARCHAR(40) NOT NULL COMMENT 'VIEW/EXPORT/CALC/APPROVE/CORRECT/SLIP_VIEW',
    TARGET_TYPE    VARCHAR(40) NULL,
    TARGET_ID      VARCHAR(64) NULL,
    PERIOD         VARCHAR(6) NULL,
    DETAIL         VARCHAR(500) NULL,
    OP_AT          DATETIME NOT NULL,
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_PAY_AUDIT_PERIOD (PERIOD, OP_AT)
) COMMENT='薪酬审计日志（只插不改）';

