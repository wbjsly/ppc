-- ---------- 2. 个税：税率表（官方月度税率，YEAR 维度）/ 人年累计 / 专项附加扣除 ----------
CREATE TABLE IF NOT EXISTS hr_iit_tax_table (
    ID             VARCHAR(32) NOT NULL,
    YEAR           INT NOT NULL,
    LEVEL_NO       INT NOT NULL COMMENT '级数 1-7',
    LOWER_BOUND    DECIMAL(12,2) NOT NULL COMMENT '累计应纳税所得额下限（月度换算口径）',
    UPPER_BOUND    DECIMAL(12,2) NULL COMMENT '上限（NULL=无上限）',
    RATE           DECIMAL(6,4) NOT NULL COMMENT '预扣率',
    QUICK_DEDUCT   DECIMAL(12,2) NOT NULL COMMENT '速算扣除数',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_IIT_TAX (YEAR, LEVEL_NO)
) COMMENT='个税月度税率表（累计预扣法适用）';

-- 官方七级超额累进（2019 年起现行口径，公开数据）
INSERT IGNORE INTO hr_iit_tax_table (ID, YEAR, LEVEL_NO, LOWER_BOUND, UPPER_BOUND, RATE, QUICK_DEDUCT, CREATE_BY, CREATE_DATE, DEL_FLAG, VER_NO)
SELECT CONCAT('IIT-2026-', LEVEL_NO), 2026, LEVEL_NO, LB, UB, RT, QD, 'migration', NOW(), '0', 0
FROM (
    SELECT 1 AS LEVEL_NO, 0 AS LB, 36000 AS UB, 0.0300 AS RT, 0 AS QD
    UNION SELECT 2, 36000, 144000, 0.1000, 2520
    UNION SELECT 3, 144000, 300000, 0.2000, 16920
    UNION SELECT 4, 300000, 420000, 0.2500, 31920
    UNION SELECT 5, 420000, 660000, 0.3000, 52920
    UNION SELECT 6, 660000, 960000, 0.3500, 85920
    UNION SELECT 7, 960000, NULL, 0.4500, 181920
) t
WHERE NOT EXISTS (SELECT 1 FROM hr_iit_tax_table WHERE YEAR=2026 AND LEVEL_NO=t.LEVEL_NO);

CREATE TABLE IF NOT EXISTS hr_iit_cumulative (
    ID             VARCHAR(32) NOT NULL,
    EMP_ID         VARCHAR(32) NOT NULL,
    YEAR           INT NOT NULL,
    CUM_GROSS      DECIMAL(14,2) NOT NULL DEFAULT 0 COMMENT '累计应发（含免税外收入口径简化为应发）',
    CUM_DEDUCT     DECIMAL(14,2) NOT NULL DEFAULT 0 COMMENT '累计专项扣除（社保公积金个人）',
    CUM_SPECIAL    DECIMAL(14,2) NOT NULL DEFAULT 0 COMMENT '累计专项附加扣除',
    CUM_TAX_PAID   DECIMAL(14,2) NOT NULL DEFAULT 0 COMMENT '累计已预扣税额',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_IIT_CUM (EMP_ID, YEAR)
) COMMENT='个税累计预扣台账（人×年，月度滚动）';

CREATE TABLE IF NOT EXISTS hr_iit_special_deduction (
    ID             VARCHAR(32) NOT NULL,
    EMP_ID         VARCHAR(32) NOT NULL,
    DEDUCT_TYPE    VARCHAR(30) NOT NULL COMMENT 'CHILD_EDUCATION/CONTINUE_EDU/HOUSING_LOAN/HOUSING_RENT/SUPPORT_ELDERLY/INFANT_CARE',
    MONTHLY_AMOUNT DECIMAL(10,2) NOT NULL COMMENT '每月分摊金额',
    STATUS         VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE/DISABLED',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_HR_IIT_SD_EMP (EMP_ID, STATUS)
) COMMENT='专项附加扣除（员工自助端维护，税务同步留桩）';

