-- ---------- 1. 社保公积金政策（城市×年度×险种行式；DEMO 占位行供冒烟演示） ----------
CREATE TABLE IF NOT EXISTS hr_social_policy (
    ID             VARCHAR(32) NOT NULL,
    CITY           VARCHAR(50) NOT NULL COMMENT '缴纳地（对应 hr_employee.SOCIAL_PLACE）',
    YEAR           INT NOT NULL COMMENT '政策年度',
    INS_TYPE       VARCHAR(20) NOT NULL COMMENT 'PENSION/MEDICAL/UNEMPLOY/INJURY/MATERNITY/PROVIDENT',
    BASE_MIN       DECIMAL(12,2) NOT NULL COMMENT '缴费基数下限（保底）',
    BASE_MAX       DECIMAL(12,2) NOT NULL COMMENT '缴费基数上限（封顶）',
    EMP_RATE       DECIMAL(6,4) NOT NULL COMMENT '单位比例（0.16=16%）',
    EE_RATE        DECIMAL(6,4) NOT NULL COMMENT '个人比例',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_SOCIAL_POLICY (CITY, YEAR, INS_TYPE)
) COMMENT='社保公积金属地政策';

