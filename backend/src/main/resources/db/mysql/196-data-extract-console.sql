CREATE TABLE IF NOT EXISTS erp_bi_datasource (
  ID                VARCHAR(32)  NOT NULL COMMENT '主键',
  NAME              VARCHAR(64)  NOT NULL COMMENT '数据源名称（唯一）',
  TYPE              VARCHAR(16)  NOT NULL DEFAULT 'DB' COMMENT '类型：DB 数据库 / API / FILE（仅登记形态，不建真实外连）',
  DB_NAME           VARCHAR(64)  DEFAULT NULL COMMENT '逻辑库名（DB 类型登记）',
  CONN_ENC          VARCHAR(512) DEFAULT NULL COMMENT '连接信息加密存储（AES，明文不出接口，FR-4.10-2-1）',
  SCHEMA_SNAPSHOT   LONGTEXT     DEFAULT NULL COMMENT 'schema 快照 JSON（information_schema 列清单，变更检测基准 BR-4.10-15）',
  SNAPSHOT_AT       DATETIME     DEFAULT NULL COMMENT '快照采集时间',
  STATUS            VARCHAR(24)  NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE / SCHEMA_CHANGED 结构已变更暂停 / DISABLED',
  REMARK            VARCHAR(500) DEFAULT NULL,
  CREATE_BY         VARCHAR(64)  DEFAULT NULL,
  CREATE_DATE       DATETIME     DEFAULT NULL,
  UPDATE_BY         VARCHAR(64)  DEFAULT NULL,
  UPDATE_DATE       DATETIME     DEFAULT NULL,
  DEL_FLAG          VARCHAR(1)   NOT NULL DEFAULT '0',
  VER_NO            INT          NOT NULL DEFAULT 0,
  PRIMARY KEY (ID),
  UNIQUE KEY UK_BI_DS_NAME (NAME),
  KEY IDX_BI_DS_STATUS (STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='逻辑数据源登记（14.2.1 抽取配置，spec bi-extract-console）';

CREATE TABLE IF NOT EXISTS erp_bi_extract_config (
  ID               VARCHAR(32)  NOT NULL COMMENT '主键',
  CODE             VARCHAR(64)  NOT NULL COMMENT '配置编码（数据源内唯一）',
  NAME             VARCHAR(128) NOT NULL COMMENT '配置名称',
  DATASOURCE_ID    VARCHAR(32)  NOT NULL COMMENT '数据源 ID',
  TEMPLATE_ID      VARCHAR(32)  NOT NULL COMMENT '报表模板 ID（仅 PUBLISHED 可绑定，service 校验）',
  MODE             VARCHAR(16)  NOT NULL DEFAULT 'FULL' COMMENT 'FULL 全量 / INCREMENTAL 增量（水位线推进）',
  WATERMARK_FIELD  VARCHAR(64)  DEFAULT NULL COMMENT '增量水位字段（须在模板列清单内，MAX(query) 推进）',
  LAST_WATERMARK   VARCHAR(64)  DEFAULT NULL COMMENT '当前水位（断点续抽定位，BR-4.10-13）',
  SEQ              INT          NOT NULL DEFAULT 10 COMMENT 'DAG 层序（同批上游 SEQ 小，未就绪下游挂起）',
  STATUS           VARCHAR(16)  NOT NULL DEFAULT 'ENABLED' COMMENT 'ENABLED / DISABLED（schema 变更时由引擎跳过）',
  REMARK           VARCHAR(500) DEFAULT NULL,
  CREATE_BY        VARCHAR(64)  DEFAULT NULL,
  CREATE_DATE      DATETIME     DEFAULT NULL,
  UPDATE_BY        VARCHAR(64)  DEFAULT NULL,
  UPDATE_DATE      DATETIME     DEFAULT NULL,
  DEL_FLAG         VARCHAR(1)   NOT NULL DEFAULT '0',
  VER_NO           INT          NOT NULL DEFAULT 0,
  PRIMARY KEY (ID),
  UNIQUE KEY UK_BI_EXC_CFG (DATASOURCE_ID, CODE),
  KEY IDX_BI_EXC_CFG_STATUS (STATUS, SEQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='模板驱动抽取配置（14.2.1，spec bi-extract-console）';

CREATE TABLE IF NOT EXISTS erp_bi_extract_batch (
  ID          VARCHAR(32) NOT NULL COMMENT '主键',
  BATCH_NO    VARCHAR(32) NOT NULL COMMENT '批次号 yyyyMMdd',
