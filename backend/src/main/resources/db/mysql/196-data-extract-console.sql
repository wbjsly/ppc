  READY_AT    DATETIME    DEFAULT NULL COMMENT '就绪时间（依赖方前置）',
  REMARK      VARCHAR(500) DEFAULT NULL,
  CREATE_BY   VARCHAR(64) DEFAULT NULL,
  CREATE_DATE DATETIME    DEFAULT NULL,
  UPDATE_BY   VARCHAR(64) DEFAULT NULL,
  UPDATE_DATE DATETIME    DEFAULT NULL,
  DEL_FLAG    VARCHAR(1)  NOT NULL DEFAULT '0',
  VER_NO      INT         NOT NULL DEFAULT 0,
  PRIMARY KEY (ID),
  UNIQUE KEY UK_BI_EXC_BATCH (BATCH_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='抽取批次（14.2.1 数据就绪标志，spec bi-extract-console）';

CREATE TABLE IF NOT EXISTS erp_bi_extract_run (
  ID             VARCHAR(32) NOT NULL COMMENT '主键',
  BATCH_DATE     DATE        NOT NULL COMMENT '批次日',
  BATCH_NO       VARCHAR(32) NOT NULL COMMENT '批次号',
  CONFIG_ID      VARCHAR(32) NOT NULL COMMENT '抽取配置 ID',
  SEQ            INT         NOT NULL DEFAULT 10 COMMENT 'DAG 层序（快照自配置）',
  STATUS         VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING / RUNNING / READY / PAUSED 波动暂停 / FAILED',
  ROW_COUNT      BIGINT      NOT NULL DEFAULT 0 COMMENT '本批行数',
  PREV_ROW_COUNT BIGINT      DEFAULT NULL COMMENT '前次同配置行数（波动判定对照，BR-4.10-12）',
  WATERMARK      VARCHAR(64) DEFAULT NULL COMMENT '本批推进水位（断点）',
  RETRY          INT         NOT NULL DEFAULT 0 COMMENT '重试次数（≤ API_RETRY_MAX=3）',
  ERROR_MSG      VARCHAR(500) DEFAULT NULL,
  MANUAL_CONFIRM TINYINT(1)  NOT NULL DEFAULT 0 COMMENT '波动暂停人工确认标记',
  ELAPSED_MS     BIGINT      DEFAULT NULL COMMENT '执行耗时毫秒',
  FINISHED_AT    DATETIME    DEFAULT NULL,
  CREATE_BY      VARCHAR(64) DEFAULT NULL,
  CREATE_DATE    DATETIME    DEFAULT NULL,
  UPDATE_BY      VARCHAR(64) DEFAULT NULL,
  UPDATE_DATE    DATETIME    DEFAULT NULL,
  DEL_FLAG       VARCHAR(1)  NOT NULL DEFAULT '0',
  VER_NO         INT         NOT NULL DEFAULT 0,
  PRIMARY KEY (ID),
  UNIQUE KEY UK_BI_EXC_RUN (BATCH_DATE, CONFIG_ID),
  KEY IDX_BI_EXC_RUN_STATUS (BATCH_DATE, STATUS, SEQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='抽取批次执行记录（14.2.1，波动/断点/重试，spec bi-extract-console）';

CREATE TABLE IF NOT EXISTS erp_bi_quality_rule (
  ID            VARCHAR(32)  NOT NULL COMMENT '主键',
  NAME          VARCHAR(128) NOT NULL COMMENT '规则名称',
  RULE_TYPE     VARCHAR(16)  NOT NULL COMMENT 'NOT_NULL 必填非空率 / RECONCILE 跨表勾稽 / RANGE 数值范围',
  DATASOURCE_ID VARCHAR(32)  DEFAULT NULL COMMENT '所属数据源（批次自动校验按此归集；NULL=仅手动）',
  TARGET_TABLE  VARCHAR(128) DEFAULT NULL COMMENT '目标表（NOT_NULL/RANGE 必填，[A-Za-z0-9_]）',
  TARGET_COLUMN VARCHAR(64)  DEFAULT NULL COMMENT '目标字段（NOT_NULL/RANGE 必填）',
  LEFT_SQL      TEXT         DEFAULT NULL COMMENT '勾稽左侧合计 SQL（RECONCILE，SELECT-only）',
  RIGHT_SQL     TEXT         DEFAULT NULL COMMENT '勾稽右侧合计 SQL（RECONCILE）',
  NOT_NULL_MIN  DECIMAL(6,3) NOT NULL DEFAULT 99.900 COMMENT '非空率阈值百分比（默认 99.9，BR-4.10-14）',
  TOLERANCE     DECIMAL(18,4) NOT NULL DEFAULT 0 COMMENT '勾稽容差（|左-右|≤容差 通过）',
  MIN_VAL       DECIMAL(18,4) DEFAULT NULL COMMENT '范围下限（RANGE）',
  MAX_VAL       DECIMAL(18,4) DEFAULT NULL COMMENT '范围上限（RANGE）',
  SEVERE_LEVEL  VARCHAR(8)   NOT NULL DEFAULT 'SEVERE' COMMENT 'SEVERE 阻断就绪+告警 / WARN 告警放行',
  STATUS        VARCHAR(16)  NOT NULL DEFAULT 'ENABLED' COMMENT 'ENABLED / DISABLED',
  REMARK        VARCHAR(500) DEFAULT NULL,
  CREATE_BY     VARCHAR(64)  DEFAULT NULL,
  CREATE_DATE   DATETIME     DEFAULT NULL,
  UPDATE_BY     VARCHAR(64)  DEFAULT NULL,
  UPDATE_DATE   DATETIME     DEFAULT NULL,
  DEL_FLAG      VARCHAR(1)   NOT NULL DEFAULT '0',
  VER_NO        INT          NOT NULL DEFAULT 0,
  PRIMARY KEY (ID),
  KEY IDX_BI_QC_RULE_STATUS (STATUS, RULE_TYPE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='数据质量规则（14.2.3，spec bi-quality-check）';

CREATE TABLE IF NOT EXISTS erp_bi_quality_result (
  ID           VARCHAR(32)  NOT NULL COMMENT '主键',
  BATCH_NO     VARCHAR(32)  DEFAULT NULL COMMENT '批次号（手动校验为空）',
  RULE_ID      VARCHAR(32)  NOT NULL COMMENT '规则 ID',
  RULE_NAME    VARCHAR(128) NOT NULL COMMENT '规则名称快照（报告不随规则改名漂移）',
  RULE_TYPE    VARCHAR(16)  NOT NULL COMMENT '类型快照',
  TARGET_DESC  VARCHAR(255) DEFAULT NULL COMMENT '目标描述（表.字段 / 勾稽两侧）',
  EXPECTED     VARCHAR(64)  DEFAULT NULL COMMENT '期望值（阈值/容差/范围）',
  ACTUAL       VARCHAR(64)  DEFAULT NULL COMMENT '实测值（非空率/差值/越界行数）',
  CONCLUSION   VARCHAR(8)   NOT NULL COMMENT 'PASS / FAIL',
  SEVERE_LEVEL VARCHAR(8)   NOT NULL DEFAULT 'SEVERE' COMMENT '严重级别快照',
  EXEC_BY      VARCHAR(64)  DEFAULT NULL,
  EXEC_AT      DATETIME     DEFAULT NULL,
  ERROR_MSG    VARCHAR(500) DEFAULT NULL,
  CREATE_BY    VARCHAR(64)  DEFAULT NULL,
  CREATE_DATE  DATETIME     DEFAULT NULL,
  UPDATE_BY    VARCHAR(64)  DEFAULT NULL,
  UPDATE_DATE  DATETIME     DEFAULT NULL,
  DEL_FLAG     VARCHAR(1)   NOT NULL DEFAULT '0',
  VER_NO       INT          NOT NULL DEFAULT 0,
  PRIMARY KEY (ID),
  KEY IDX_BI_QC_RESULT_BATCH (BATCH_NO, CONCLUSION),
  KEY IDX_BI_QC_RESULT_RULE (RULE_ID, EXEC_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='数据质量校验报告（14.2.3，≥180 天，spec bi-quality-check）';

