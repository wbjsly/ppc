-- ---- erp_bi_perm_rule 幂等加 MASK_STYLE（类型化掩码样式，design D3）----
SET @c1 := (SELECT COUNT(*) FROM information_schema.COLUMNS
            WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='erp_bi_perm_rule' AND COLUMN_NAME='MASK_STYLE');
SET @s1 := IF(@c1=0, 'ALTER TABLE erp_bi_perm_rule ADD COLUMN MASK_STYLE VARCHAR(16) DEFAULT ''GENERIC'' COMMENT ''掩码样式：PHONE/ID_CARD/SALARY/BANK/GENERIC'' AFTER ACTION', 'SELECT 1');
PREPARE st1 FROM @s1; EXECUTE st1; DEALLOCATE PREPARE st1;

