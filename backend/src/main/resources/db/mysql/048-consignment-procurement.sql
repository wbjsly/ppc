-- 048-consignment-procurement.sql
-- 寄售采购 VMI（2.8.1）+ 领料出库（4.5.2），change add-consignment-procurement design D1/D11
-- 1) 九表：VMI 协议头/行、寄售库存、领料单头/行、结算单头/行、处置建议单、告警
-- 2) 增列：erp_fin_ap_invoice.SETTLE_ID（VMI 发票关联结算单，design D8）
-- 3) 菜单 PERM：M2-8-1、M4-5-2（design D11）
-- 幂等：CREATE IF NOT EXISTS / information_schema+PREPARE / UPDATE 天然幂等（045/046/047 范式）

-- ---------- 1) VMI 寄售协议头（FR-4.2-8-1） ----------
CREATE TABLE IF NOT EXISTS erp_proc_vmi_agreement (
    ID VARCHAR(64) NOT NULL,
    AGREE_NO VARCHAR(32) NOT NULL COMMENT '协议编号 VM+yyyyMMdd+流水',
    SUPPLIER_ID VARCHAR(64) NOT NULL,
    SUPPLIER_NAME VARCHAR(128) DEFAULT NULL,
    SETTLE_CYCLE VARCHAR(8) NOT NULL DEFAULT 'MONTH' COMMENT '结算周期 WEEK 周 / MONTH 月',
    TRANSFER_TIME VARCHAR(16) NOT NULL DEFAULT 'ISSUE' COMMENT '物权转移时点（本期仅 ISSUE 领用时转移）',
    EFFECTIVE_DATE DATE NOT NULL COMMENT '生效日期',
    EXPIRE_DATE DATE NOT NULL COMMENT '失效日期（下达卡控：须 >= PO 交期，BR-4.2-35）',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT 草稿 / EFFECTIVE 生效 / EXPIRED 过期 / DISABLED 停用',
    REMARK VARCHAR(255) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_VMI_AGREE_NO (AGREE_NO),
    KEY IDX_VMI_AGREE_SUP (SUPPLIER_ID, STATUS),
    KEY IDX_VMI_AGREE_DATE (EXPIRE_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- ---------- 2) VMI 协议行：寄售物料清单 + 水位 + 价格条款 ----------
CREATE TABLE IF NOT EXISTS erp_proc_vmi_agreement_line (
    ID VARCHAR(64) NOT NULL,
    AGREE_ID VARCHAR(64) NOT NULL,
    ITEM_CODE VARCHAR(64) NOT NULL,
    ITEM_NAME VARCHAR(128) DEFAULT NULL,
    UNIT VARCHAR(16) DEFAULT NULL,
    MIN_QTY DECIMAL(18,3) NOT NULL DEFAULT 0 COMMENT '最低库存水位（低于生成补货建议，FR-4.2-8-1）',
    MAX_QTY DECIMAL(18,3) NOT NULL DEFAULT 0 COMMENT '最高库存水位（超出阻断收货，BR-4.2-36；0=不限）',
    UNIT_PRICE DECIMAL(18,4) NOT NULL COMMENT '协议单价（领用计价基准）',
    PRICE_START DATE NOT NULL COMMENT '价格条款起（领用日须在条款内，C-4.2-09）',
    PRICE_END DATE NOT NULL COMMENT '价格条款止',
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_VMI_AGREE_L_AGREE (AGREE_ID, ITEM_CODE),
    KEY IDX_VMI_AGREE_L_ITEM (ITEM_CODE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- ---------- 3) 寄售库存（物权=供应商，独立分账，BR-4.2-01 / design D1） ----------
CREATE TABLE IF NOT EXISTS erp_inv_vmi_stock (
    ID VARCHAR(64) NOT NULL,
    ITEM_CODE VARCHAR(64) NOT NULL,
    ITEM_NAME VARCHAR(128) DEFAULT NULL,
    BATCH_NO VARCHAR(64) NOT NULL DEFAULT '',
    SUPPLIER_ID VARCHAR(64) NOT NULL,
