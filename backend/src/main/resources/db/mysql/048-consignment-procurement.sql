    KEY IDX_MI_DATE (CREATE_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- ---------- 5) 领料单行（FIFO 配批结果固化） ----------
CREATE TABLE IF NOT EXISTS erp_inv_material_issue_line (
    ID VARCHAR(64) NOT NULL,
    ISSUE_ID VARCHAR(64) NOT NULL,
    LINE_NO INT NOT NULL DEFAULT 1,
    ITEM_CODE VARCHAR(64) NOT NULL,
    ITEM_NAME VARCHAR(128) DEFAULT NULL,
    BATCH_NO VARCHAR(64) NOT NULL DEFAULT '',
    QTY DECIMAL(18,4) NOT NULL COMMENT '本批领用数量',
    STOCK_TYPE VARCHAR(8) NOT NULL DEFAULT 'OWN' COMMENT 'OWN / VMI（头冗余便于检索）',
    SUPPLIER_ID VARCHAR(64) DEFAULT NULL COMMENT '寄售供应商（VMI 行）',
    UNIT_PRICE DECIMAL(18,4) DEFAULT NULL COMMENT '领用时点协议价（VMI 行，物权转移计价）',
    AMOUNT DECIMAL(18,2) DEFAULT NULL COMMENT '金额 = QTY × UNIT_PRICE（VMI 行）',
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
