-- ---------- 10) 增列：发票关联 VMI 结算单 / 领料单供应商（design D8，幂等） ----------
SET @ddl = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE()
        AND TABLE_NAME = 'erp_fin_ap_invoice'
        AND COLUMN_NAME = 'SETTLE_ID') = 0,
    'ALTER TABLE erp_fin_ap_invoice
       ADD COLUMN SETTLE_ID VARCHAR(64) DEFAULT NULL
         COMMENT ''关联 VMI 结算单 ID（CONSIGN PO 发票必填，MODIFIED three-way-match）''',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

SET @ddl = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE()
        AND TABLE_NAME = 'erp_inv_material_issue'
        AND COLUMN_NAME = 'SUPPLIER_ID') = 0,
    'ALTER TABLE erp_inv_material_issue
       ADD COLUMN SUPPLIER_ID VARCHAR(64) DEFAULT NULL COMMENT ''寄售供应商（VMI 领用必填）'',
       ADD COLUMN SUPPLIER_NAME VARCHAR(128) DEFAULT NULL COMMENT ''寄售供应商名称''',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

