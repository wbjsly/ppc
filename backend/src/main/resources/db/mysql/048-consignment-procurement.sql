-- ---------- 6) VMI 结算单头（FR-4.2-8-4 / BR-4.2-38 双确认，design D7） ----------
CREATE TABLE IF NOT EXISTS erp_proc_vmi_settlement (
    ID VARCHAR(64) NOT NULL,
    SETTLE_NO VARCHAR(32) NOT NULL COMMENT '结算单号 VS+yyyyMMdd+流水',
    SUPPLIER_ID VARCHAR(64) NOT NULL,
    SUPPLIER_NAME VARCHAR(128) DEFAULT NULL,
    PERIOD_START DATE NOT NULL COMMENT '结算期间起',
    PERIOD_END DATE NOT NULL COMMENT '结算期间止',
    SETTLE_CYCLE VARCHAR(8) NOT NULL DEFAULT 'MONTH',
    CALC_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '逐笔汇总 = Σ(领用量 × 领用时点协议价)',
    TRIAL_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '期末价试算金额',
    DIFF_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '差额 = CALC − TRIAL',
    DIFF_RATE DECIMAL(10,6) NOT NULL DEFAULT 0 COMMENT '差率 = |差额| / TRIAL（TRIAL=0 取 0/1）',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT / ON_HOLD 超容差挂起 / CONFIRMED / INVOICED / CANCELLED',
    PM_CONFIRM_BY VARCHAR(64) DEFAULT NULL COMMENT '采购员确认人（双确认之一）',
    PM_CONFIRM_AT DATETIME DEFAULT NULL,
    SUPPLIER_CONFIRM_BY VARCHAR(128) DEFAULT NULL COMMENT '供应商确认人（线下确认登记，design D7）',
    SUPPLIER_CONFIRM_AT DATETIME DEFAULT NULL,
    SUPPLIER_CONFIRM_WAY VARCHAR(64) DEFAULT NULL COMMENT '确认方式：邮件/传真/对账单回签等',
    REMARK VARCHAR(255) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_VMI_SETTLE_NO (SETTLE_NO),
    KEY IDX_VMI_SETTLE_SUP (SUPPLIER_ID, STATUS),
    KEY IDX_VMI_SETTLE_PERIOD (PERIOD_END)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

