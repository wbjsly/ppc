-- ---------- 2. 科目映射配置（成本中心→费用科目；缺配置 L4 提示并阻断凭证不阻断发薪） ----------
CREATE TABLE IF NOT EXISTS hr_pay_account_mapping (
    ID             VARCHAR(32) NOT NULL,
    MAPPING_TYPE   VARCHAR(20) NOT NULL COMMENT 'COST_CENTER/FIXED',
    MAPPING_KEY    VARCHAR(50) NOT NULL COMMENT '成本中心编码或 FIXED 键',
    ACCOUNT_CODE   VARCHAR(32) NOT NULL COMMENT '费用/资产科目编码',
    REMARK         VARCHAR(200) NULL,
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_PAY_ACCT_MAP (MAPPING_TYPE, MAPPING_KEY)
) COMMENT='工资凭证科目映射（成本中心→费用科目）';

