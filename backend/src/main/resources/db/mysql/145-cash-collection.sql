-- 145-cash-collection.sql
-- add-payment-collection：统一收付款中心（design D2/D3/D5：三表 + 预收科目 2205 + 存量迁移 + 旧表下线 + M8-4 菜单）
-- 幂等：CREATE TABLE IF NOT EXISTS + INSERT IGNORE + information_schema 判存/PREPARE；迁移带版本标记跳过重迁

-- ---------- 1. 统一收付款单（design D2） ----------
CREATE TABLE IF NOT EXISTS erp_fin_cash_doc (
    ID VARCHAR(64) NOT NULL,
    DOC_NO VARCHAR(32) NOT NULL COMMENT 'IN: RC+yyyyMMdd+流水 / OUT: PY+yyyyMMdd+流水',
    DIRECTION VARCHAR(4) NOT NULL COMMENT 'IN 收款 / OUT 付款',
    PARTY_TYPE VARCHAR(16) NOT NULL COMMENT 'CUSTOMER / SUPPLIER（BR-4.6-17）',
    PARTY_ID VARCHAR(64) NOT NULL,
    PARTY_CODE VARCHAR(32) DEFAULT NULL,
    PARTY_NAME VARCHAR(128) DEFAULT NULL,
    AMOUNT DECIMAL(18,2) NOT NULL COMMENT '单据金额',
    DEDUCT_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0.00 COMMENT 'SCAR 抵扣合计（OUT 应付侧，保留 payment-execution 口径）',
    ACTUAL_AMOUNT DECIMAL(18,2) NOT NULL COMMENT '实收/实付 = AMOUNT − DEDUCT（银行余额变动额）',
    CURRENCY VARCHAR(8) NOT NULL DEFAULT 'CNY' COMMENT '币种（C-4.6-11 核销一致性基准）',
    PAY_METHOD VARCHAR(16) NOT NULL COMMENT '电汇/支票/商业汇票/银行承兑汇票/现金（BR-4.6-20）',
    BANK_ACCOUNT_ID VARCHAR(64) NOT NULL,
    ACCOUNT_NAME VARCHAR(64) DEFAULT NULL,
    ACCOUNT_NO VARCHAR(32) DEFAULT NULL,
    PAY_DATE DATE NOT NULL COMMENT '收付款日期（凭证日期，BR-4.6-19）',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'PENDING_POST' COMMENT 'DRAFT/PENDING_POST/POSTED/RECONCILED/VOID',
    REQ_ID VARCHAR(64) DEFAULT NULL COMMENT '关联付款/预付申请（OUT 侧，可空）',
    REQ_NO VARCHAR(32) DEFAULT NULL,
    PAY_TYPE VARCHAR(16) DEFAULT NULL COMMENT 'PAYMENT 应付 / PREPAY 预付（OUT 侧凭证分流）',
    DEDUCT_IDS TEXT COMMENT '抵扣扣款单 ID 集合 JSON（OUT 应付侧）',
    VOUCHER_ID VARCHAR(64) DEFAULT NULL COMMENT '过账资金凭证 ID（RCT/PAY/PPR）',
    CROSS_PERIOD VARCHAR(1) NOT NULL DEFAULT '0' COMMENT '1=跨期核销（C-4.6-02，自动标记）',
    WRITEOFF_STATE VARCHAR(16) NOT NULL DEFAULT 'NONE' COMMENT 'NONE/PENDING/APPROVED/DONE/REJECTED',
    APPR_ID VARCHAR(64) COMMENT '跨期核销审批实例锚',
    REJECT_REASON VARCHAR(255),
    REMARK VARCHAR(512),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_CASH_DOC_NO (DOC_NO),
    KEY IDX_FIN_CASH_DOC_PARTY (PARTY_ID, PAY_DATE),
    KEY IDX_FIN_CASH_DOC_STATUS (STATUS),
    KEY IDX_FIN_CASH_DOC_DATE (PAY_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='统一收付款单（M8-4-1/8.4-2）';

-- ---------- 2. 统一核销表（design D2/D4：target 区分 AR/AP；SETTLE 预付冲抵 DOC 可空） ----------
CREATE TABLE IF NOT EXISTS erp_fin_cash_writeoff (
    ID VARCHAR(64) NOT NULL,
    WO_NO VARCHAR(32) NOT NULL COMMENT '核销单号',
    DOC_ID VARCHAR(64) DEFAULT NULL COMMENT '收付款单 ID（SETTLE 预付冲抵为空）',
    DOC_NO VARCHAR(32) DEFAULT NULL,
    TARGET_TYPE VARCHAR(8) NOT NULL COMMENT 'AR / AP',
    TARGET_ID VARCHAR(64) NOT NULL COMMENT '被核销发票 ID',
    TARGET_NO VARCHAR(64) DEFAULT NULL,
    AMOUNT DECIMAL(18,2) NOT NULL COMMENT '核销金额',
    WRITEOFF_MODE VARCHAR(16) NOT NULL DEFAULT 'AUTO' COMMENT 'AUTO/MANUAL/SETTLE/REBATE',
    WRITEOFF_DATE DATE NOT NULL,
    CUSTOMER_ID VARCHAR(64) DEFAULT NULL COMMENT '客户维度（AR 核销/返利冲抵，信用统计口径）',
    DUE_DATE DATE DEFAULT NULL COMMENT '目标应收到期日（ON_TIME 判定基准）',
    ON_TIME CHAR(1) DEFAULT NULL COMMENT '1=按时（WRITEOFF_DATE ≤ DUE_DATE，BR-4.3-15/16）',
    WRITE_TYPE VARCHAR(16) DEFAULT NULL COMMENT '业务子类：RECEIPT/PAYMENT/REBATE 等（沿旧表口径）',
    REMARK VARCHAR(500),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_CASH_WO_NO (WO_NO),
    KEY IDX_FIN_CASH_WO_DOC (DOC_ID),
    KEY IDX_FIN_CASH_WO_TARGET (TARGET_TYPE, TARGET_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='统一核销记录（FIFO 内核单一事实源）';

-- ---------- 3. 银行回单（design D2/D8：M8-4-3 逐笔对账，M8-7 余额级复用数据源） ----------
CREATE TABLE IF NOT EXISTS erp_fin_bank_receipt (
    ID VARCHAR(64) NOT NULL,
    RECEIPT_NO VARCHAR(64) NOT NULL COMMENT '银行回单号（唯一）',
    BANK_ACCOUNT_ID VARCHAR(64) NOT NULL,
    TRADE_DATE DATE NOT NULL COMMENT '交易日期',
    DIRECTION VARCHAR(8) NOT NULL COMMENT 'RECEIVE 收 / PAY 付',
    AMOUNT DECIMAL(18,2) NOT NULL,
    COUNTERPARTY VARCHAR(128) DEFAULT NULL COMMENT '对方户名',
    SUMMARY VARCHAR(255) DEFAULT NULL COMMENT '摘要',
    SOURCE VARCHAR(8) NOT NULL DEFAULT 'MANUAL' COMMENT 'IMPORT/MANUAL',
    MATCH_STATUS VARCHAR(16) NOT NULL DEFAULT 'UNMATCHED' COMMENT 'UNMATCHED/MATCHED/EXCEPTION',
    MATCHED_DOC_ID VARCHAR(64) DEFAULT NULL COMMENT '匹配的收付款单 ID',
    MATCHED_DOC_NO VARCHAR(32) DEFAULT NULL,
    MATCHED_BY VARCHAR(64),
    MATCHED_AT DATETIME,
    EXCEPTION_REASON VARCHAR(255),
    RECONCILE_BY VARCHAR(64) COMMENT '解除匹配操作人',
    RECONCILE_AT DATETIME,
    RECONCILE_REASON VARCHAR(255),
    REMARK VARCHAR(512),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_BANK_RC_NO (RECEIPT_NO),
    KEY IDX_FIN_BANK_RC_MATCH (MATCH_STATUS),
    KEY IDX_FIN_BANK_RC_ACCT_DATE (BANK_ACCOUNT_ID, TRADE_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='银行回单（回单对账 M8-4-3）';

