-- ---------- 7) 批次预留表（tasks 8.1 提前：7.7 确认同事务生成预留依赖） ----------
CREATE TABLE IF NOT EXISTS erp_sd_reservation (
    ID VARCHAR(64) NOT NULL,
    SO_ID VARCHAR(64) NOT NULL,
    SO_NO VARCHAR(32) DEFAULT NULL,
    LINE_ID VARCHAR(64) NOT NULL COMMENT 'SO 行 ID',
    LINE_NO INT DEFAULT NULL,
    ITEM_CODE VARCHAR(64) NOT NULL,
    WAREHOUSE_CODE VARCHAR(32) NOT NULL DEFAULT 'WH-MAIN',
    -- 无批次物料用 '' 占位（8.6）
    BATCH_NO VARCHAR(64) NOT NULL DEFAULT '',
    QTY DECIMAL(18,3) NOT NULL COMMENT '预留数量',
    -- ACTIVE 生效 / CONSUMED 已消耗（发货）/ RELEASED 已释放（取消/关闭/变更减量）
    STATUS VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE/CONSUMED/RELEASED',
    -- 先到先得裁决基准（BR-4.3-24 时间戳）
    LOCK_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    RELEASED_AT DATETIME DEFAULT NULL,
    RELEASE_REASON VARCHAR(128) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_SD_RSV_SO (SO_ID, STATUS),
    KEY IDX_SD_RSV_BATCH (WAREHOUSE_CODE, ITEM_CODE, BATCH_NO, STATUS),
    KEY IDX_SD_RSV_LINE (LINE_ID, STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='SO 批次预留（BR-4.3-24/29；ATP 的 Reserved = SUM(ACTIVE)）';
