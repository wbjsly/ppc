-- ---------- 1) SO 版本与变更（tasks 7.1 后半，提前到 054） ----------

CREATE TABLE IF NOT EXISTS erp_sd_so_version (
    ID VARCHAR(64) NOT NULL,
    SO_ID VARCHAR(64) NOT NULL,
    VERSION_NO INT NOT NULL,
    -- CREATE 建单 / APPROVE 审批 / CONFIRM 确认 / CHANGE 变更 / CLOSE 关闭
    OP_TYPE VARCHAR(16) NOT NULL,
    SNAPSHOT_JSON JSON DEFAULT NULL,
    OPERATOR_ID VARCHAR(64) DEFAULT NULL,
    OPERATE_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_SD_SOV_SO (SO_ID, VERSION_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='销售订单版本快照';

CREATE TABLE IF NOT EXISTS erp_sd_so_change (
    ID VARCHAR(64) NOT NULL,
    SO_ID VARCHAR(64) NOT NULL,
    LINE_NO INT DEFAULT NULL,
    FIELD_NAME VARCHAR(64) NOT NULL,
    OLD_VALUE VARCHAR(500) DEFAULT NULL,
    NEW_VALUE VARCHAR(500) DEFAULT NULL,
    -- 重跑信用/ATP 的结论（BR-4.3-30）
    CREDIT_RERUN VARCHAR(16) DEFAULT NULL COMMENT 'PASS/FROZEN/NEED_APPROVAL',
    REASON VARCHAR(1000) DEFAULT NULL,
    OPERATOR_ID VARCHAR(64) DEFAULT NULL,
    OPERATE_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_SD_SOC_SO (SO_ID, OPERATE_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='销售订单变更记录（含信用重跑结论）';

-- ---------- 2) 应收核心两表（第 10 组提前到本文件；账龄/及时率种子与信用计算依赖） ----------

CREATE TABLE IF NOT EXISTS erp_fin_ar_invoice (
    ID VARCHAR(64) NOT NULL,
    -- AR + yyyyMMdd + 4 位流水
    AR_NO VARCHAR(32) NOT NULL COMMENT '应收单号',
    CUSTOMER_ID VARCHAR(64) NOT NULL,
    CUSTOMER_CODE VARCHAR(32) DEFAULT NULL,
    CUSTOMER_NAME VARCHAR(128) DEFAULT NULL,
    SO_ID VARCHAR(64) DEFAULT NULL,
    SO_NO VARCHAR(32) DEFAULT NULL,
    -- 应收发生日（开票/发货确认）；账龄与到期从此推算
    INVOICE_DATE DATE NOT NULL,
    DUE_DATE DATE NOT NULL COMMENT '到期日（付款条件基准）',
    AMOUNT DECIMAL(18,2) NOT NULL COMMENT '应收金额',
    PAID_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '已核销金额',
    -- UNPAID / PARTIAL / PAID / RED（红冲）
    STATUS VARCHAR(16) NOT NULL DEFAULT 'UNPAID',
    REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_AR_NO (AR_NO),
    KEY IDX_FIN_AR_CUST (CUSTOMER_ID, STATUS),
    KEY IDX_FIN_AR_DUE (DUE_DATE, STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='应收账款头（第 10 组扩展开票/核销联动）';

CREATE TABLE IF NOT EXISTS erp_fin_ar_writeoff (
    ID VARCHAR(64) NOT NULL,
    -- WO + yyyyMMdd + 4 位流水
    WO_NO VARCHAR(32) NOT NULL COMMENT '核销单号',
    AR_ID VARCHAR(64) NOT NULL,
    AR_NO VARCHAR(32) DEFAULT NULL,
    CUSTOMER_ID VARCHAR(64) NOT NULL,
    AMOUNT DECIMAL(18,2) NOT NULL COMMENT '核销/回款金额',
    -- 实际付款日 vs 应收到期日 → 及时率（BR-4.3-15）
    PAY_DATE DATE NOT NULL COMMENT '实际付款日',
    DUE_DATE DATE NOT NULL COMMENT '对应到期日',
    ON_TIME VARCHAR(1) NOT NULL DEFAULT '0' COMMENT '1 = 按时（PAY_DATE ≤ DUE_DATE）',
    -- MANUAL 人工 / AUTO FIFO 自动（第 10 组扩展）
    WRITE_TYPE VARCHAR(16) NOT NULL DEFAULT 'MANUAL',
    REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_WO_NO (WO_NO),
    KEY IDX_FIN_WO_AR (AR_ID),
    KEY IDX_FIN_WO_CUST (CUSTOMER_ID, PAY_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='应收核销/回款记录（及时率与连续逾期统计源）';

-- ---------- 3) 信用三表（tasks 6.1，spec customer-credit-control） ----------

-- 3.1 信用检查记录（BR-4.3-13 四因子快照；判定留痕）
CREATE TABLE IF NOT EXISTS erp_sd_credit_check (
    ID VARCHAR(64) NOT NULL,
    CUSTOMER_ID VARCHAR(64) NOT NULL,
    CUSTOMER_CODE VARCHAR(32) DEFAULT NULL,
    CUSTOMER_NAME VARCHAR(128) DEFAULT NULL,
    -- 关联 SO（建单即检时非空；客户级体检可空）
    SO_ID VARCHAR(64) DEFAULT NULL,
    SO_NO VARCHAR(32) DEFAULT NULL,
    ORDER_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '本次订单金额（四因子之一）',
    -- 四因子快照（BR-4.3-13）
    CREDIT_LIMIT_TOTAL DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '信用额度（含有效临时额度）',
    AR_BALANCE DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '应收账款余额',
    SO_RESERVED DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '未清 SO 预占金额',
    CONSIGN_OCCUPIED DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '寄售专项额度占用',
    AVAILABLE DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '可用额度 = 额度 − AR − 预占 − 本次 − 寄售',
    -- 账龄（BR-4.3-14）
    AR_OVER90 DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '超期 90 天以上应收',
    OVER90_RATIO DECIMAL(6,4) DEFAULT NULL COMMENT '超 90 天占比',
    -- 付款及时率（BR-4.3-15）
    PAY_ON_TIME_RATE DECIMAL(6,4) DEFAULT NULL COMMENT '近 12 个月及时率',
    -- PASS 通过 / FROZEN 信用冻结 / NEED_APPROVAL 需审批（账龄超比）
    RESULT VARCHAR(16) NOT NULL COMMENT 'PASS/FROZEN/NEED_APPROVAL',
    REASON VARCHAR(1000) DEFAULT NULL,
    -- 账龄分析报告 JSON（L2 派发信用管理员时附）
    AGING_REPORT JSON DEFAULT NULL,
    CHECK_BY VARCHAR(64) DEFAULT NULL,
    CHECK_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_SD_CC_CUST (CUSTOMER_ID, CHECK_AT),
    KEY IDX_SD_CC_SO (SO_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='信用检查记录（四因子与账龄及时率快照）';

-- 3.2 信用冻结单（D5 挂起态：PREV_STATUS 回前一稳定状态；解冻不重跑审批不释放预留）
CREATE TABLE IF NOT EXISTS erp_sd_credit_freeze (
    ID VARCHAR(64) NOT NULL,
    SO_ID VARCHAR(64) NOT NULL,
    SO_NO VARCHAR(32) DEFAULT NULL,
    CUSTOMER_ID VARCHAR(64) NOT NULL,
    CUSTOMER_NAME VARCHAR(128) DEFAULT NULL,
    CREDIT_CHECK_ID VARCHAR(64) DEFAULT NULL COMMENT '触发的信用检查记录',
    GAP_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '缺口金额 = −可用额度（预收目标）',
    -- FROZEN 冻结中 / UNFROZEN 已解冻
    STATUS VARCHAR(16) NOT NULL DEFAULT 'FROZEN',
    -- 冻结时 SO 的前一稳定状态（D5：审批前 → 回待审批；已确认 → 回已确认）
    PREV_STATUS VARCHAR(16) DEFAULT NULL COMMENT '前一稳定状态',
    -- 触发原因：额度不足 / 账龄超比需审批
    FREEZE_REASON VARCHAR(32) NOT NULL COMMENT 'LIMIT/AGING',
    FROZEN_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    -- 解冻：PREPAY 预收到账 / SPECIAL 信用特批 / MANUAL 人工（账龄审批通过）
    UNFREEZE_METHOD VARCHAR(16) DEFAULT NULL,
    UNFREEZE_NO VARCHAR(32) DEFAULT NULL COMMENT '《SO 解冻确认单》编号 UF-...',
    UNFROZEN_BY VARCHAR(64) DEFAULT NULL,
    UNFROZEN_AT DATETIME DEFAULT NULL,
    UNFREEZE_REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_SD_CF_SO (SO_ID, STATUS),
    KEY IDX_SD_CF_CUST (CUSTOMER_ID, STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='信用冻结单（挂起态与解冻确认）';

-- 3.3 预收款通知与到账登记（FR-4.3-2-6/2-7，BR-4.3-17）
CREATE TABLE IF NOT EXISTS erp_sd_prepayment_notice (
    ID VARCHAR(64) NOT NULL,
    -- PN + yyyyMMdd + 4 位流水
    NOTICE_NO VARCHAR(32) NOT NULL COMMENT '预收款通知单号',
    FREEZE_ID VARCHAR(64) NOT NULL COMMENT '关联冻结单',
    SO_ID VARCHAR(64) NOT NULL COMMENT '关联 SO',
    SO_NO VARCHAR(32) DEFAULT NULL,
    CUSTOMER_ID VARCHAR(64) NOT NULL,
    CUSTOMER_NAME VARCHAR(128) DEFAULT NULL,
    GAP_AMOUNT DECIMAL(18,2) NOT NULL COMMENT '预收目标金额 = 缺口',
    -- 通知留痕（通知销售员与客户）
    NOTIFY_SALES_AT DATETIME DEFAULT NULL,
    NOTIFY_CUSTOMER_AT DATETIME DEFAULT NULL,
    -- 到账登记（销售/客服登记）与财务确认（FINANCE_MGR/ADMIN）
    RECEIVED_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '累计到账登记金额',
    RECEIVED_AT DATETIME DEFAULT NULL,
    CONFIRM_BY VARCHAR(64) DEFAULT NULL COMMENT '财务确认人（仅 FINANCE_MGR/ADMIN）',
    CONFIRM_AT DATETIME DEFAULT NULL,
    -- SETTLED 已足额并解冻 / REGISTERED 已登记待确认 / NOTIFIED 已通知 / PENDING 待通知
    STATUS VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/NOTIFIED/REGISTERED/SETTLED',
    REMAIN_AMOUNT DECIMAL(18,2) DEFAULT NULL COMMENT '尚差金额（登记后计算）',
    REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_SD_PN_NO (NOTICE_NO),
    KEY IDX_SD_PN_FREEZE (FREEZE_ID),
    KEY IDX_SD_PN_STATUS (STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='预收款通知单与到账登记';

