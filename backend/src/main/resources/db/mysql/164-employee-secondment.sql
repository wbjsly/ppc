-- ---------- 1. 外派/借调单 ----------

CREATE TABLE IF NOT EXISTS hr_secondment (
    ID             VARCHAR(32) NOT NULL,
    SEC_NO         VARCHAR(32) NOT NULL COMMENT 'SEC+yyyyMMdd-序号',
    CHG_TYPE       VARCHAR(10) NOT NULL COMMENT 'DISPATCH 外派 / SECOND 借调',
    EMP_ID         VARCHAR(32) NOT NULL,
    EMP_NAME       VARCHAR(64) NULL,
    EMP_NO         VARCHAR(32) NULL,
    SRC_LE         VARCHAR(32) NULL COMMENT '调出主体（劳动关系主体，缺省主法人）',
    TARGET_LE      VARCHAR(32) NOT NULL COMMENT '用工/新主体（LE_CODE）',
    TARGET_PLACE   VARCHAR(64) NULL COMMENT '社保缴纳地（生效变更时联动）',
    PLACE_CHANGE   CHAR(1) NOT NULL DEFAULT '0' COMMENT '1=变更缴纳地',
    COST_CENTER    VARCHAR(50) NULL COMMENT '用工主体成本中心（借调）/新成本中心（外派）',
    ORIG_COST_CENTER VARCHAR(50) NULL COMMENT '返岗恢复快照',
    SALARY_OWNER   VARCHAR(32) NULL COMMENT '薪酬发放主体（备案语义，恒=劳动关系主体）',
    COST_SHARE_PCT DECIMAL(5,2) NULL COMMENT '分摊比例 0-100（借调必填，双方确认后锁定）',
    SHARE_LOCKED   CHAR(1) NOT NULL DEFAULT '0' COMMENT '1=比例已锁定（双方确认完成）',
    ALLOWANCE_MONTHLY    DECIMAL(12,2) NULL COMMENT '补贴申请额快照',
    ALLOWANCE_STD_MONTHLY DECIMAL(12,2) NULL COMMENT '标准带出值快照（差异标注）',
    AGREEMENT_NO   VARCHAR(64) NULL COMMENT '三方协议编号（借调必填，BR-4.7-19）',
    AGREEMENT_DATE DATE NULL,
    START_DATE     DATE NOT NULL,
    END_DATE       DATE NOT NULL,
    REMIND_FLAG    CHAR(1) NOT NULL DEFAULT '0' COMMENT '1=15天返岗提醒已发',
    STATUS         VARCHAR(20) NOT NULL COMMENT 'DRAFT/CONFIRMED_OUT/CONFIRMED_IN/HR_REVIEWED/REVIEWING/REVIEW_DIFF/APPROVING/EFFECTED/EXTENDING/RETURNING/RETURNED/EXPIRED_ALERT/REJECTED/VOID',
    CONFIRM_OUT_JSON VARCHAR(500) NULL COMMENT '调出确认（意见/人/时间）',
    CONFIRM_IN_JSON  VARCHAR(500) NULL COMMENT '调入确认',
    HR_OPINION     VARCHAR(500) NULL,
    REVIEW1_JSON   VARCHAR(500) NULL,
    REVIEW1_BY     VARCHAR(64) NULL,
    REVIEW1_AT     DATETIME NULL,
    REVIEW2_JSON   VARCHAR(500) NULL,
    REVIEW2_BY     VARCHAR(64) NULL,
    REVIEW2_AT     DATETIME NULL,
    REVIEW_DIFF_JSON VARCHAR(500) NULL,
    ADJUDICATE_NOTE VARCHAR(500) NULL,
    APPR_ID        VARCHAR(32) NULL,
    EXTEND_MONTHS_TOTAL INT NOT NULL DEFAULT 0 COMMENT '累计延期月数（BR-4.7-05）',
    EFFECTIVE_AT   DATETIME NULL,
    RETURN_AT      DATETIME NULL,
    LINK_PENDING   CHAR(1) NOT NULL DEFAULT '0' COMMENT '1=生效联动失败待重试',
    LINK_NOTE      VARCHAR(500) NULL,
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_SEC_NO (SEC_NO),
    KEY IDX_HR_SEC_EMP (EMP_ID, STATUS),
    KEY IDX_HR_SEC_STATUS (STATUS, END_DATE)
) COMMENT='外派/借调单（FR-4.7-7，10.8.1/10.8.2 共用）';

-- ---------- 2. 外派补贴标准 ----------

CREATE TABLE IF NOT EXISTS hr_dispatch_allowance_std (
    ID             VARCHAR(32) NOT NULL,
    PLACE          VARCHAR(64) NOT NULL COMMENT '缴纳地/外派地',
    GRADE_ID       VARCHAR(32) NOT NULL COMMENT '职级',
    MONTHLY        DECIMAL(12,2) NOT NULL COMMENT '月补贴标准',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_SEC_STD (PLACE, GRADE_ID)
) COMMENT='外派补贴标准（城市×职级，FR-4.7-7-3 自动带出）';

