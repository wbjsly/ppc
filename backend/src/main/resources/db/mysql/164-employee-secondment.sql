-- ---------- 3. 最小通用附件 ----------

CREATE TABLE IF NOT EXISTS erp_sys_attachment (
    ID             VARCHAR(32) NOT NULL,
    BIZ_TYPE       VARCHAR(40) NOT NULL COMMENT '业务类型（如 SECONDTM_AGREEMENT）',
    BIZ_ID         VARCHAR(32) NOT NULL COMMENT '业务主键',
    FILE_NAME      VARCHAR(255) NOT NULL COMMENT '原始文件名',
    STORE_PATH     VARCHAR(300) NOT NULL COMMENT '存储路径（本地盘 UUID 文件名）',
    FILE_SIZE      BIGINT NULL COMMENT '字节数',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_SYS_ATT (BIZ_TYPE, BIZ_ID, FILE_NAME),
    KEY IDX_SYS_ATT_BIZ (BIZ_TYPE, BIZ_ID)
) COMMENT='通用附件（最小能力：上传/查询/下载）';

