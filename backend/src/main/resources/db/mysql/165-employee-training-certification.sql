-- ============================================================
-- 165 培训认证（add-training-certification）
--   ①hr_cert_category 证书类别字典 ②hr_employee_cert 员工证书台账
--   ③hr_train_plan 培训计划 ④hr_train_task 参训任务
--   ⑤hr_skill_matrix 技能矩阵 ⑥培训凭证科目与映射 ⑦SysParam ⑧DEMO 类别种子
-- ============================================================

-- ---------- 1. 证书类别字典 ----------

CREATE TABLE IF NOT EXISTS hr_cert_category (
    ID             VARCHAR(32) NOT NULL,
    CATE_CODE      VARCHAR(32) NOT NULL COMMENT 'CATE+流水，创建后不可改',
    CATE_NAME      VARCHAR(64) NOT NULL,
    IS_KEY         CHAR(1) NOT NULL DEFAULT '0' COMMENT '1=关键岗位资格认证（BR-4.7-06 门禁范围）',
    SKILL_CODE     VARCHAR(32) NULL COMMENT '对应技能编码（技能矩阵 CERT 来源）',
    SKILL_LEVEL    VARCHAR(16) NULL COMMENT '默认技能等级',
    STATUS         VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE/DISABLED（停用不可被新证书引用）',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_CATE_CODE (CATE_CODE),
    KEY IDX_HR_CATE_SKILL (SKILL_CODE)
) COMMENT='证书类别字典（qualification-certification，关键标记定门禁范围）';

-- ---------- 2. 员工证书台账 ----------

CREATE TABLE IF NOT EXISTS hr_employee_cert (
    ID             VARCHAR(32) NOT NULL,
    EMP_ID         VARCHAR(32) NOT NULL,
    EMP_NAME       VARCHAR(64) NULL,
    EMP_NO         VARCHAR(20) NULL,
    CATE_ID        VARCHAR(32) NOT NULL,
    CATE_NAME      VARCHAR(64) NULL COMMENT '冗余快照（类别改名不影响历史）',
    CERT_NO        VARCHAR(64) NULL COMMENT '证书编号',
    ISSUE_ORG      VARCHAR(128) NULL COMMENT '发证机关',
    VALID_FROM     DATE NULL,
    VALID_TO       DATE NULL COMMENT '到期日（翻转与门禁判定基准）',
    STATUS         VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                   COMMENT 'PENDING/VALID/REVIEW_DUE/EXPIRED/REJECTED/ARCHIVED',
    REVIEW_OPINION VARCHAR(500) NULL COMMENT '审核驳回意见',
    AUDIT_BY       VARCHAR(64) NULL,
    AUDIT_AT       DATETIME NULL,
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_HR_CERT_EMP (EMP_ID, STATUS),
    KEY IDX_HR_CERT_CATE (CATE_ID, STATUS),
    KEY IDX_HR_CERT_EXPIRY (STATUS, VALID_TO)
) COMMENT='员工资格认证台账（BR-4.7-06 到期预警与排班门禁判定源）';

-- ---------- 3. 培训计划 ----------

CREATE TABLE IF NOT EXISTS hr_train_plan (
    ID             VARCHAR(32) NOT NULL,
    PLAN_NO        VARCHAR(32) NOT NULL COMMENT 'TP+年度+流水，创建后不可改',
    PLAN_YEAR      INT NOT NULL,
    COURSE_NAME    VARCHAR(128) NOT NULL,
    TRAIN_TYPE     VARCHAR(16) NULL COMMENT '内训/外训/线上',
    SKILL_CODE     VARCHAR(32) NULL COMMENT '关联技能（培训通过写入技能矩阵）',
    SKILL_LEVEL    VARCHAR(16) NULL COMMENT '通过后授予等级',
    TARGET_TYPE    VARCHAR(10) NOT NULL COMMENT 'DEPT=按部门快照 / MEMBERS=人员清单',
    TARGET_VALUE   VARCHAR(500) NOT NULL COMMENT 'DEPT:部门ID / MEMBERS:逗号分隔员工ID',
    DATE_FROM      DATE NULL,
    DATE_TO        DATE NULL,
    DUE_DATE       DATE NULL COMMENT '完成期限（催办基准）',
    PLAN_HOURS     DECIMAL(6,1) NULL,
    PASS_SCORE     INT NULL COMMENT '合格线（缺省 TRAIN_PASS_SCORE）',
    BUDGET         DECIMAL(12,2) NULL,
    ACTUAL_COST    DECIMAL(12,2) NULL COMMENT '实际费用（登记触发计提凭证）',
    OWNER          VARCHAR(64) NULL COMMENT '负责 HR',
    STATUS         VARCHAR(20) NOT NULL DEFAULT 'PUBLISHED' COMMENT 'PUBLISHED/CANCELLED',
    CHANGE_LOG_JSON TEXT NULL COMMENT '修改留痕（时间/人/字段/前后值）',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_PLAN_NO (PLAN_NO),
    KEY IDX_HR_PLAN_YEAR (PLAN_YEAR, STATUS)
) COMMENT='年度培训计划（training-plan-execution，编制即发布）';

-- ---------- 4. 参训任务 ----------

CREATE TABLE IF NOT EXISTS hr_train_task (
    ID             VARCHAR(32) NOT NULL,
    PLAN_ID        VARCHAR(32) NOT NULL,
    EMP_ID         VARCHAR(32) NOT NULL,
    EMP_NAME       VARCHAR(64) NULL,
    EMP_NO         VARCHAR(20) NULL,
    DEPT_ID        VARCHAR(32) NULL COMMENT '展开时部门快照（完成率部门维度）',
    STATUS         VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                   COMMENT 'PENDING/CONFIRMED/COMPLETED/FAILED/CANCELLED',
    ATTEND         VARCHAR(16) NULL COMMENT '出勤：正常/缺勤/迟到',
    SCORE          DECIMAL(6,1) NULL COMMENT '考试成绩',
    ACTUAL_HOURS   DECIMAL(6,1) NULL COMMENT '实际学时',
    REMARK         VARCHAR(500) NULL,
    CONFIRM_AT     DATETIME NULL COMMENT '员工自助确认时间',
    CONFIRM_SRC    VARCHAR(16) NULL COMMENT 'SELF（员工确认）',
    RESULT_BY      VARCHAR(64) NULL COMMENT 'HR 登记人',
    RESULT_AT      DATETIME NULL,
    RESULT_HIST_JSON TEXT NULL COMMENT '结果修改留痕（前后成绩/学时/人/时间）',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_TASK_PLAN_EMP (PLAN_ID, EMP_ID),
    KEY IDX_HR_TASK_EMP (EMP_ID, STATUS)
) COMMENT='参训任务（UK=计划×员工，重复展开幂等）';

-- ---------- 5. 技能矩阵 ----------

CREATE TABLE IF NOT EXISTS hr_skill_matrix (
    ID             VARCHAR(32) NOT NULL,
    EMP_ID         VARCHAR(32) NOT NULL,
    SKILL_CODE     VARCHAR(32) NOT NULL,
    SKILL_LEVEL    VARCHAR(16) NULL,
    SOURCE         VARCHAR(10) NOT NULL COMMENT 'CERT/TRAIN（last-writer-wins，失效按来源隔离）',
    SOURCE_DOC     VARCHAR(64) NULL COMMENT '来源单据（证书ID/计划ID）',
    STATUS         VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE/EXPIRED',
    CREATE_BY      VARCHAR(64) NULL,
    CREATE_DATE    DATETIME NULL,
    UPDATE_BY      VARCHAR(64) NULL,
    UPDATE_DATE    DATETIME NULL,
    DEL_FLAG       CHAR(1) NOT NULL DEFAULT '0',
    VER_NO         INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_HR_SKILL_EMP (EMP_ID, SKILL_CODE),
    KEY IDX_HR_SKILL_CODE (SKILL_CODE, STATUS)
) COMMENT='人员技能矩阵（skill-matrix，CERT/TRAIN 双来源）';

