-- 207: 本地适配 i18n 17 域（add-i18n-l10n）
-- 四新表 + 参数四枚 + 三语种子键（zh 全量 / en 全译 / ja 部分留缺口演示）
-- 幂等：可重复执行（CREATE IF NOT EXISTS + INSERT IGNORE）

CREATE TABLE IF NOT EXISTS erp_i18n_pack (
    ID varchar(64) NOT NULL PRIMARY KEY,
    PACK_NO varchar(32) NOT NULL COMMENT '语义化版本 Major.Minor.Patch',
    LOCALE varchar(16) NOT NULL COMMENT 'zh-CN/en-US/ja-JP',
    STATUS varchar(16) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT/PRECHECK/REVIEWING/APPROVED/CANARY/ARCHIVED',
    SOURCE_VERSION varchar(32) NULL COMMENT '基线版本',
    FALLBACK_POLICY_JSON longtext NULL COMMENT '回退策略：默认语种/视觉标记/埋点开关',
    CANARY_PCT int NULL DEFAULT 10,
    CANARY_WINDOW_H int NULL DEFAULT 24,
    RENDER_ERR_CNT int NOT NULL DEFAULT 0,
    RENDER_REQ_CNT int NOT NULL DEFAULT 0,
    REMARK varchar(500) NULL,
    CREATE_BY varchar(64) NULL, CREATE_DATE datetime NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY varchar(64) NULL, UPDATE_DATE datetime NULL DEFAULT CURRENT_TIMESTAMP,
    DEL_FLAG varchar(1) NOT NULL DEFAULT '0', VER_NO int NOT NULL DEFAULT 0,
    UNIQUE UK_I18N_PACK (LOCALE, PACK_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='i18n 语言包版本';

CREATE TABLE IF NOT EXISTS erp_i18n_key (
    ID varchar(64) NOT NULL PRIMARY KEY,
    KEY_NAME varchar(200) NOT NULL,
    MODULE varchar(64) NULL,
    PRIORITY varchar(8) NOT NULL DEFAULT 'P1' COMMENT 'P0/P1/P2/P3',
    CONTEXT_NOTE varchar(500) NULL COMMENT '上下文说明',
    CHAR_LIMIT int NULL,
    SOURCE_TEXT text NULL COMMENT 'zh-CN 源语',
    TARGET_TEXT text NULL COMMENT '译文（空=缺口）',
    LOCALE varchar(16) NOT NULL,
    PACK_NO varchar(32) NOT NULL DEFAULT '0.0.0',
    CREATE_BY varchar(64) NULL, CREATE_DATE datetime NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY varchar(64) NULL, UPDATE_DATE datetime NULL DEFAULT CURRENT_TIMESTAMP,
    DEL_FLAG varchar(1) NOT NULL DEFAULT '0', VER_NO int NOT NULL DEFAULT 0,
    UNIQUE UK_I18N_KEY (KEY_NAME, LOCALE, PACK_NO),
    KEY IDX_I18N_KEY_MOD (MODULE, PRIORITY)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='i18n 翻译键值';

CREATE TABLE IF NOT EXISTS erp_i18n_gap (
    ID varchar(64) NOT NULL PRIMARY KEY,
    KEY_NAME varchar(200) NOT NULL,
    MODULE varchar(64) NULL,
    PRIORITY varchar(8) NOT NULL DEFAULT 'P2',
    FIRST_HIT_AT datetime NULL,
    HIT_COUNT int NOT NULL DEFAULT 0,
    STATUS varchar(16) NOT NULL DEFAULT 'OPEN' COMMENT 'OPEN/TRANSLATING/CLOSED',
    CLOSED_AT datetime NULL,
    CREATE_BY varchar(64) NULL, CREATE_DATE datetime NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY varchar(64) NULL, UPDATE_DATE datetime NULL DEFAULT CURRENT_TIMESTAMP,
    DEL_FLAG varchar(1) NOT NULL DEFAULT '0', VER_NO int NOT NULL DEFAULT 0,
    UNIQUE UK_I18N_GAP (KEY_NAME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='i18n 翻译缺口台账';

CREATE TABLE IF NOT EXISTS erp_i18n_compliance_field (
    ID varchar(64) NOT NULL PRIMARY KEY,
    PACK_CODE varchar(32) NOT NULL COMMENT 'JP_INVOICE/EU_VAT/CN_TAX',
    REG_PLACE varchar(64) NULL COMMENT '法人主体注册地映射（JP/EU/CN）',
    FIELD_NAME varchar(64) NOT NULL,
    COLUMN_NAME varchar(64) NOT NULL COMMENT '既有表列名（复用不新建）',
    FORMAT_REGEX varchar(500) NULL,
    REQUIRED varchar(1) NOT NULL DEFAULT '1',
    ERROR_HINT varchar(200) NULL,
    SORT_NO int NOT NULL DEFAULT 0,
    CREATE_BY varchar(64) NULL, CREATE_DATE datetime NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY varchar(64) NULL, UPDATE_DATE datetime NULL DEFAULT CURRENT_TIMESTAMP,
    DEL_FLAG varchar(1) NOT NULL DEFAULT '0', VER_NO int NOT NULL DEFAULT 0,
    UNIQUE UK_I18N_CF (PACK_CODE, FIELD_NAME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='i18n 本地合规字段包';

INSERT IGNORE INTO erp_sys_param (ID, PARAM_KEY, PARAM_VALUE, VALUE_TYPE, PARAM_GROUP, REMARK, CREATE_BY, CREATE_DATE, DEL_FLAG, VER_NO)
SELECT UUID(), t.k, t.v, t.t, 'I18N', t.r, 'migration-207', NOW(), '0', 0
FROM (SELECT 'TRANSLATION_COVERAGE_MIN' k, '99' v, 'INT' t, '翻译覆盖率门槛%' r
      UNION SELECT 'I18N_FALLBACK_LOCALE', 'zh-CN', 'STRING', '回退默认语种'
      UNION SELECT 'TAX_ROUNDING_SCOPE', 'LINE', 'STRING', '多行计税口径 LINE/AGG'
      UNION SELECT 'I18N_CANARY_WINDOW_HOURS', '24', 'INT', '灰度观察窗口小时') t
WHERE NOT EXISTS (SELECT 1 FROM erp_sys_param p WHERE p.PARAM_KEY=t.k AND p.DEL_FLAG='0');

