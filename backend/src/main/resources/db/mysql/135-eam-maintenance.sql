-- ---------- 5. 维护计划（design D1：周期 D/W/M/Q/Y + 备件清单 JSON 快照） ----------
CREATE TABLE IF NOT EXISTS erp_eam_maint_plan (
    ID VARCHAR(64) NOT NULL,
    PLAN_NO VARCHAR(32) NOT NULL COMMENT '计划编号 MP+yyyyMMdd+4位流水',
    CARD_ID VARCHAR(64) NOT NULL COMMENT '资产卡片',
    CARD_NO VARCHAR(32) NOT NULL,
    ITEM_NAME VARCHAR(255) NOT NULL COMMENT '维护项目',
    CYCLE VARCHAR(8) NOT NULL COMMENT '周期 D/W/M/Q/Y',
    STANDARD VARCHAR(500) COMMENT '维护标准',
    SPARES_JSON VARCHAR(2000) COMMENT '所需备件清单 [{itemCode,itemName,qty}]',
    EST_HOURS DECIMAL(10,2) COMMENT '预计工时',
    CRITICAL_FLAG VARCHAR(1) NOT NULL DEFAULT '0' COMMENT '关键设备 1=是(须主管审批)',
    APPROVAL_STATUS VARCHAR(16) NOT NULL DEFAULT 'APPROVED' COMMENT 'NOT_REQUIRED/APPROVED/PENDING_APPROVE/REJECTED',
    EFFECTIVE_FLAG VARCHAR(1) NOT NULL DEFAULT '1' COMMENT '生效 1/停用 0',
    NEXT_PLAN_DATE DATE COMMENT '下次计划日',
    REMARK VARCHAR(500),
    CREATE_BY VARCHAR(64), CREATE_DATE DATETIME, UPDATE_BY VARCHAR(64), UPDATE_DATE DATETIME,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0', VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_EAM_MP_NO (PLAN_NO),
    KEY IDX_EAM_MP_CARD (CARD_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- ---------- 6. 统一工单（design D1/D3：PREVENTIVE/REPAIR + 状态机 + 幂等键 + 三构成成本 + BOM 快照） ----------
CREATE TABLE IF NOT EXISTS erp_eam_work_order (
    ID VARCHAR(64) NOT NULL,
    WO_NO VARCHAR(32) NOT NULL COMMENT '工单号 WO+yyyyMMdd+4位流水',
    WO_TYPE VARCHAR(12) NOT NULL COMMENT 'PREVENTIVE/REPAIR',
    SRC_TYPE VARCHAR(12) NOT NULL DEFAULT 'MANUAL' COMMENT 'PLAN/REPORT/IOT/MANUAL(IOT 仅预留)',
    IDEMPOTENT_KEY VARCHAR(128) DEFAULT NULL COMMENT '幂等键 设备编号+预警事件号/计划ID+计划日',
    PLAN_ID VARCHAR(64) COMMENT '维护计划(PLAN 来源)',
    PLAN_DATE DATE COMMENT '计划日(顺延后)',
    REPORT_ID VARCHAR(64) COMMENT '报修单(REPAIR 来源)',
    CARD_ID VARCHAR(64) NOT NULL,
    CARD_NO VARCHAR(32) NOT NULL,
    FAULT_SYMPTOM VARCHAR(255) COMMENT '故障现象(REPAIR;BR-19 同现象统计)',
    FAULT_TIME DATETIME COMMENT '故障发现时间',
    IMPACT_SCOPE VARCHAR(255) COMMENT '影响范围',
    PLAN_DESC VARCHAR(500) COMMENT '维护/维修内容要求',
    RESOLVE_PLAN VARCHAR(16) COMMENT '维修方案 SELF/OUTSOURCE(REPAIR)',
    OUTSOURCE_VENDOR VARCHAR(128) COMMENT '外协单位',
    OUTSOURCE_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '外协成本(手工)',
    OUTSOURCE_ACCEPT_FILE VARCHAR(255) COMMENT '外协验收单附件(BR-20 关闭前置)',
    BOM_JSON VARCHAR(2000) COMMENT '备件清单快照 [{itemCode,itemName,qty}](超领校验基准)',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/ASSIGNED/EXECUTING/PENDING_ACCEPT/CLOSED/CANCELLED',
    ASSIGNEE VARCHAR(64) COMMENT '指派维修人',
    EST_HOURS DECIMAL(10,2) COMMENT '预计工时',
    EXEC_DESC VARCHAR(1000) COMMENT '实际维护/维修内容',
    ISSUE_DESC VARCHAR(500) COMMENT '发现的问题',
    PARTS_CHANGED VARCHAR(500) COMMENT '更换部件',
    PARENT_WO_NO VARCHAR(32) COMMENT '父工单号(子工单)',
    ACCEPT_BY_OP VARCHAR(64) COMMENT '验收-操作员(REPAIR 双确认之一)',
    ACCEPT_BY_ENG VARCHAR(64) COMMENT '验收-设备工程师',
    ACCEPT_DATE DATETIME,
    RESULT_EVAL VARCHAR(16) COMMENT '维护结果评价 GOOD/OK/BAD(FR-4.13-3-5)',
    SPARE_COST DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '备件成本(已过账 MAINT 领料合计)',
    LABOR_COST DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '人工成本(工时×费率)',
    LABOR_RATE_PENDING VARCHAR(1) NOT NULL DEFAULT '0' COMMENT '费率待调整(缺参)',
    TOTAL_COST DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '工单成本合计',
    OVERHAUL_ASSESS_FLAG VARCHAR(1) NOT NULL DEFAULT '0' COMMENT 'BR-19 大修评估触发',
    ASSESS_STATUS VARCHAR(16) DEFAULT NULL COMMENT '评估 PENDING_APPROVE/APPROVED/REJECTED(归档后解冻)',
    CLOSE_BY VARCHAR(64), CLOSE_DATE DATETIME, CANCEL_REASON VARCHAR(255),
    REMARK VARCHAR(500),
    CREATE_BY VARCHAR(64), CREATE_DATE DATETIME, UPDATE_BY VARCHAR(64), UPDATE_DATE DATETIME,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0', VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_EAM_WO_NO (WO_NO),
    UNIQUE KEY UK_EAM_WO_IDEM (IDEMPOTENT_KEY),
    KEY IDX_EAM_WO_CARD (CARD_ID),
    KEY IDX_EAM_WO_STATUS (STATUS),
    KEY IDX_EAM_WO_PARENT (PARENT_WO_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

