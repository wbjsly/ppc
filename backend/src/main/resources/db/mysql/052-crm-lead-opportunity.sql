CREATE TABLE IF NOT EXISTS erp_crm_lead (
    ID VARCHAR(64) NOT NULL,
    -- LD + yyyyMMdd + 4 位流水
    LEAD_NO VARCHAR(32) NOT NULL COMMENT '线索编号',
    -- 展会/网络/渠道/转介绍/主动开拓（FR-4.8-1-1 预设渠道枚举）
