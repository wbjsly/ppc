    SCORE_URGENCY INT DEFAULT NULL COMMENT '时间紧迫度 1-5（权重 15%）',
    SCORE_COMPETE INT DEFAULT NULL COMMENT '竞争态势 1-5（权重 10%）',
    SCORE DECIMAL(6,2) DEFAULT NULL COMMENT '加权总分（0-100）',
    GRADE VARCHAR(2) DEFAULT NULL COMMENT '等级 A≥80 / B 60-79 / C 40-59 / D <40',
    SCORE_MODEL_ID VARCHAR(64) DEFAULT NULL COMMENT '所用评分模型',
    SCORE_MODEL_VERSION INT DEFAULT NULL COMMENT '所用模型版本（可回溯）',
    SCORE_AT DATETIME DEFAULT NULL,
    OWNER_ID VARCHAR(64) DEFAULT NULL COMMENT '跟进负责人（BR-4.8-08 单人锁定）',
    OWNER_NAME VARCHAR(64) DEFAULT NULL,
    ASSIGNED_AT DATETIME DEFAULT NULL COMMENT '分配时间（3 工作日提醒基准）',
    POOL_FLAG VARCHAR(1) NOT NULL DEFAULT '0' COMMENT '1 = 在线索池待指派',
    LAST_FOLLOWUP_AT DATETIME DEFAULT NULL COMMENT '最后跟进时间（30 天回收基准）',
    REMIND_AT DATETIME DEFAULT NULL COMMENT '超 3 工作日未跟进的最近提醒时间（FR-4.8-1-3）',
    NEXT_PLAN_DATE DATE DEFAULT NULL COMMENT '下次跟进计划日（按等级节奏生成）',
    -- OPEN 跟进中 / CONVERTED 已转化商机 / CLOSED 已关闭 / RECYCLED 已回收待指派
