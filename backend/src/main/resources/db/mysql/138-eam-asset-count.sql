-- ---------- 8. 盘点明细（design D1/D3：物理快照列 + 实盘列 + 差异列；BR-29） ----------
CREATE TABLE IF NOT EXISTS erp_eam_count_line (
    ID VARCHAR(64) NOT NULL,
    PLAN_ID VARCHAR(64) NOT NULL,
    CNT_NO VARCHAR(32) NOT NULL,
    -- 快照列（清单下发时冻结，比对基准）
    CARD_ID VARCHAR(64) COMMENT '快照来源卡片（SURPLUS 行为空）',
    CARD_NO VARCHAR(32) NOT NULL COMMENT '卡号（盘盈行= SURPLUS- 流水合成号）',
    SNAP_NAME VARCHAR(255) COMMENT '快照资产名称',
    SNAP_DEPT VARCHAR(128) COMMENT '快照使用部门',
    SNAP_CC VARCHAR(32) COMMENT '快照成本中心',
    SNAP_LOCATION VARCHAR(128) COMMENT '快照存放地点',
    SNAP_CATEGORY VARCHAR(32) COMMENT '快照资产分类',
    SNAP_COST DECIMAL(18,2) COMMENT '快照原值',
    SNAP_ACCUM DECIMAL(18,2) COMMENT '快照累计折旧',
    SNAP_NBV DECIMAL(18,2) COMMENT '快照 NBV（盘亏核销基准 BR-28）',
    SNAP_STATUS VARCHAR(16) COMMENT '快照卡片状态',
    -- 实盘列
    ACTUAL_STATUS VARCHAR(20) COMMENT 'IN_USE/IDLE/DAMAGED/PENDING_SCRAP（四实态）/MISSING 盘亏/SURPLUS 盘盈/UNKNOWN 无标签待确认',
    ACTUAL_NOTE VARCHAR(500) COMMENT '实盘备注（无标签描述/序列号等）',
    COUNTED_BY VARCHAR(64),
    COUNTED_AT DATETIME,
    COUNT_METHOD VARCHAR(12) COMMENT 'SCAN/MANUAL/IMPORT',
    REFRESH_LAST_USED_FLAG VARCHAR(1) NOT NULL DEFAULT '0' COMMENT '实盘在用刷新 LAST_USED_AT（S-4.13-13）',
    -- 差异列
    DIFF_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    DIFF_TYPE VARCHAR(20) COMMENT 'OVER 盘盈/SHORT 盘亏/TAG_ISSUE 标签异常/STATUS_CONFLICT 账实冲突/PENDING_CONFIRM 待确认',
    REASON VARCHAR(500) COMMENT '差异原因（位置错误/标签错误/未及时转资/已报废未销账/查无原因升级）',
    EVIDENCE VARCHAR(500) COMMENT '证据（报废审批单/调拨单等）',
    REMARK VARCHAR(500),
    CREATE_BY VARCHAR(64), CREATE_DATE DATETIME, UPDATE_BY VARCHAR(64), UPDATE_DATE DATETIME,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0', VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_EAM_CNTLINE (PLAN_ID, CARD_NO),
    KEY IDX_EAM_CNTLINE_PLAN (PLAN_ID),
    KEY IDX_EAM_CNTLINE_DIFF (DIFF_TYPE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- ---------- 9. 差异单（design D1/D5：四类差异 + 自动带价 + 责任认定 + 账务锚 + 状态机） ----------
CREATE TABLE IF NOT EXISTS erp_eam_count_diff (
    ID VARCHAR(64) NOT NULL,
    PLAN_ID VARCHAR(64) NOT NULL,
    CNT_NO VARCHAR(32) NOT NULL,
    LINE_ID VARCHAR(64) NOT NULL,
    DIFF_TYPE VARCHAR(20) NOT NULL COMMENT 'OVER/SHORT/TAG_ISSUE/STATUS_CONFLICT',
    -- 卡片与快照回显
    CARD_ID VARCHAR(64),
    CARD_NO VARCHAR(32),
    SNAP_NAME VARCHAR(255),
    SNAP_DEPT VARCHAR(128),
    SNAP_CC VARCHAR(32),
    SNAP_CATEGORY VARCHAR(32),
    SNAP_COST DECIMAL(18,2),
    SNAP_ACCUM DECIMAL(18,2),
    SNAP_NBV DECIMAL(18,2),
    -- 差异金额与盘盈计价（BR-27）
    DIFF_AMOUNT DECIMAL(18,2) COMMENT '盘亏=NBV / 盘盈=入账价值',
    SUGGESTED_PRICE DECIMAL(18,2) COMMENT '自动带价：同分类 12 月转资原值均价',
    PRICE_BASIS VARCHAR(500) COMMENT '计价依据（均价来源/评估报告编号）',
    -- 审批锚（D2 逐单分级）
    APPR_ID VARCHAR(64),
    -- 责任认定（BR-28）
    LIABILITY_TYPE VARCHAR(16) COMMENT 'NONE 无人为/COMPENSATE 责任人赔偿/INSURANCE 保险理赔（桩位）',
    LIABILITY_PERSON VARCHAR(64) COMMENT '责任人',
    COMPENSATE_AMOUNT DECIMAL(18,2) COMMENT '赔偿/理赔金额',
    LIABILITY_BASIS VARCHAR(500) COMMENT '认定依据留痕',
    -- 账务锚（D5）
    ADJUST_STATUS VARCHAR(16) NOT NULL DEFAULT 'NONE' COMMENT 'NONE/SUSPENDED 挂账/POSTED 核销完成',
    VOUCHER_ID VARCHAR(64) COMMENT '凭证（挂账或核销）',
    FROZEN_FLAG VARCHAR(1) NOT NULL DEFAULT '0' COMMENT '1=已冻结卡片调拨处置（BR-30）',
    -- 状态机 PENDING→APPROVED→LIABILITY_PENDING→READY_TO_POST→POSTED→CLOSED
    STATUS VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    REJECT_REASON VARCHAR(500),
    REMARK VARCHAR(500),
    CREATE_BY VARCHAR(64), CREATE_DATE DATETIME, UPDATE_BY VARCHAR(64), UPDATE_DATE DATETIME,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0', VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_EAM_CNTDIFF_PLAN (PLAN_ID),
    KEY IDX_EAM_CNTDIFF_LINE (LINE_ID),
    KEY IDX_EAM_CNTDIFF_STATUS (STATUS),
    KEY IDX_EAM_CNTDIFF_TYPE (DIFF_TYPE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

