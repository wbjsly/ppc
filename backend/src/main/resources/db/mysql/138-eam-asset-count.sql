-- ---------- 6. 盘点计划（design D1：范围/基准日/方式/状态机/覆盖率/报告审批锚） ----------
CREATE TABLE IF NOT EXISTS erp_eam_count_plan (
    ID VARCHAR(64) NOT NULL,
    CNT_NO VARCHAR(32) NOT NULL COMMENT '盘点单号 CNT+yyyyMMdd+4位流水',
    COUNT_TYPE VARCHAR(12) NOT NULL COMMENT 'FULL 全面 / SAMPLE 抽样',
    BASE_DATE DATE NOT NULL COMMENT '盘点基准日（BR-29 快照锚）',
    METHOD VARCHAR(12) NOT NULL DEFAULT 'SCAN' COMMENT 'SCAN 标签扫描 / MANUAL 手工对账',
    PLAN_DESC VARCHAR(500) COMMENT '盘点说明',
    START_DATE DATE COMMENT '盘点开始日',
    END_DATE DATE COMMENT '盘点结束日',
    STATUS VARCHAR(20) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT→ISSUED→COUNTING→DIFF_REVIEW→ADJUSTING→CLOSED',
    TOTAL_QTY INT NOT NULL DEFAULT 0 COMMENT '应盘行数（下发时快照行数）',
    COUNTED_QTY INT NOT NULL DEFAULT 0 COMMENT '已盘行数（覆盖率分子，回写）',
    COVERAGE_RATE DECIMAL(7,4) COMMENT '覆盖率（结案校验 BR-26）',
    REPORT_STATUS VARCHAR(16) NOT NULL DEFAULT 'NONE' COMMENT 'NONE/PENDING/APPROVED（报告归档审批）',
    REPORT_APPR_ID VARCHAR(64) COMMENT '报告归档审批实例',
    REPORT_SUMMARY VARCHAR(2000) COMMENT '盘点总结报告（覆盖率/差异率/原因分析/改进建议）',
    REJECT_REASON VARCHAR(500),
    REMARK VARCHAR(500),
    CREATE_BY VARCHAR(64), CREATE_DATE DATETIME, UPDATE_BY VARCHAR(64), UPDATE_DATE DATETIME,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0', VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_EAM_CNT_NO (CNT_NO),
    KEY IDX_EAM_CNT_STATUS (STATUS),
    KEY IDX_EAM_CNT_BASE (BASE_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

