-- 148-expense-reimbursement.sql
-- add-expense-reimbursement：费用报销与借款冲销（M8-8，4.6-7）+ 预提待摊（M8-9，4.6-8）
-- design D1：八表 + 科目种子（1299 替代被内部往来占用的 1221，用户决策 A）+ 费用映射种子 + 菜单 PERM
-- 幂等：CREATE TABLE IF NOT EXISTS + INSERT IGNORE + NOT EXISTS 判存

-- ---------- 1. 费用类型与科目映射（决策③，FR-4.6-7-5 映射缺失 422 的配置源） ----------
CREATE TABLE IF NOT EXISTS erp_fin_expense_type (
    ID VARCHAR(64) NOT NULL,
    TYPE_CODE VARCHAR(32) NOT NULL COMMENT '费用类型编码（报销行引用）',
    TYPE_NAME VARCHAR(64) NOT NULL,
    ACCOUNT_CODE VARCHAR(32) NOT NULL COMMENT '费用科目编码（凭证分录取数，缺失/停用 422）',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE/DISABLED（停用后新报销行不可引用，历史不受影响）',
    REMARK VARCHAR(255),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_EXPENSE_TYPE_CODE (TYPE_CODE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='费用类型-科目映射（M8-8，spec expense-reimbursement）';

-- ---------- 2. 员工借款单（FR-4.6-7-1/2，design D1：未核销余额冗余列供账龄判定与 FIFO） ----------
CREATE TABLE IF NOT EXISTS erp_fin_employee_loan (
    ID VARCHAR(64) NOT NULL,
    LOAN_NO VARCHAR(32) NOT NULL COMMENT '借款单号 LN+yyyyMMdd+流水',
    EMPLOYEE_ID VARCHAR(64) NOT NULL COMMENT '员工（erp_admin_user 即员工）',
    EMPLOYEE_NAME VARCHAR(64),
    PURPOSE VARCHAR(255) NOT NULL COMMENT '借款事由',
    AMOUNT DECIMAL(18,2) NOT NULL COMMENT '借款金额',
    EXPECTED_DATE DATE COMMENT '预计核销日期',
    OUTSTANDING_BALANCE DECIMAL(18,2) NOT NULL DEFAULT 0.00 COMMENT '未核销余额（账龄判定与 FIFO 读取源，回写列）',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT/PENDING/PAID/REJECTED（PAID=已放款挂账）',
    PAID_DATE DATE COMMENT '放款日期（账龄起算基准）',
    APPR_ID VARCHAR(64) COMMENT '审批实例锚（EmployeeLoan；超期双签=动态加签财务主管）',
    VOUCHER_ID VARCHAR(64) COMMENT '挂账凭证 ID（借 1299 / 贷 1002）',
    REMARK VARCHAR(512),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_EMP_LOAN_NO (LOAN_NO),
    KEY IDX_FIN_EMP_LOAN_EMP (EMPLOYEE_ID, STATUS),
    KEY IDX_FIN_EMP_LOAN_BAL (OUTSTANDING_BALANCE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='员工借款单（M8-8-2，spec expense-reimbursement）';

-- ---------- 3. 报销单头（FR-4.6-7-3） ----------
CREATE TABLE IF NOT EXISTS erp_fin_reimburse (
    ID VARCHAR(64) NOT NULL,
    EXP_NO VARCHAR(32) NOT NULL COMMENT '报销单号 EXP+yyyyMMdd+流水',
    EMPLOYEE_ID VARCHAR(64) NOT NULL,
    EMPLOYEE_NAME VARCHAR(64),
    TOTAL_AMOUNT DECIMAL(18,2) NOT NULL COMMENT '报销总额（=行合计，提交时校验）',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT/PENDING/APPROVED/REJECTED（审批走 ExpenseReimburse 两节点）',
    SETTLE_STATUS VARCHAR(16) NOT NULL DEFAULT 'NONE' COMMENT 'NONE/PENDING/DONE 差额结算状态（决策⑤出纳手动；PENDING=待结算）',
    SETTLE_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0.00 COMMENT '已结算合计（补付为正/退款为负累计）',
    APPR_ID VARCHAR(64) COMMENT '审批实例锚',
    VOUCHER_ID VARCHAR(64) COMMENT '报销凭证 ID（借费用 / 贷 2241）',
    OCCUR_PERIOD VARCHAR(6) COMMENT '费用归属期间 YYYYMM（凭证期间）',
    REMARK VARCHAR(512),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_REIMBURSE_NO (EXP_NO),
    KEY IDX_FIN_REIMBURSE_EMP (EMPLOYEE_ID, STATUS),
    KEY IDX_FIN_REIMBURSE_STATUS (STATUS, SETTLE_STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='费用报销单（M8-8-1，spec expense-reimbursement）';

-- ---------- 4. 报销行（发票号+销方：C-4.6-13 重复校验落点） ----------
CREATE TABLE IF NOT EXISTS erp_fin_reimburse_line (
    ID VARCHAR(64) NOT NULL,
    REIMBURSE_ID VARCHAR(64) NOT NULL,
    EXP_NO VARCHAR(32) NOT NULL COMMENT '冗余头单号（历史查询/重复校验展示原单号）',
    EXPENSE_TYPE VARCHAR(32) NOT NULL COMMENT '费用类型编码（erp_fin_expense_type.TYPE_CODE）',
    AMOUNT DECIMAL(18,2) NOT NULL,
    OCCUR_DATE DATE NOT NULL COMMENT '费用发生日期',
    COST_CENTER_ID VARCHAR(64) COMMENT '成本中心（erp_mdm_cost_center）',
    COST_CENTER_NAME VARCHAR(64),
    INVOICE_NO VARCHAR(64) NOT NULL COMMENT '发票号（C-4.6-13 唯一校验键）',
    INVOICE_VENDOR VARCHAR(128) COMMENT '发票销方（C-4.6-13 唯一校验键第二列）',
    REMARK VARCHAR(255),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    KEY IDX_FIN_REIMBURSE_LINE_HDR (REIMBURSE_ID),
    KEY IDX_FIN_REIMBURSE_INVOICE (INVOICE_NO, INVOICE_VENDOR)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='费用报销行（M8-8-1，发票重复阻断 L1）';

-- ---------- 5. 借款冲销明细（FR-4.6-7-6，BR-4.6-01 可审计回看） ----------
CREATE TABLE IF NOT EXISTS erp_fin_loan_writeoff (
    ID VARCHAR(64) NOT NULL,
    WO_NO VARCHAR(32) NOT NULL COMMENT '冲销单号 LWO+yyyyMMdd+流水',
    REIMBURSE_ID VARCHAR(64) NOT NULL,
    REIMBURSE_NO VARCHAR(32) NOT NULL,
    LOAN_ID VARCHAR(64) NOT NULL,
    LOAN_NO VARCHAR(32) NOT NULL,
    EMPLOYEE_ID VARCHAR(64) NOT NULL,
    AMOUNT DECIMAL(18,2) NOT NULL COMMENT '本次冲销金额',
    WRITEOFF_DATE DATE NOT NULL,
    VOUCHER_ID VARCHAR(64) COMMENT '冲销凭证 ID（借 2241 / 贷 1299）',
    REMARK VARCHAR(255),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_LOAN_WO_NO (WO_NO),
    KEY IDX_FIN_LOAN_WO_REIM (REIMBURSE_ID),
    KEY IDX_FIN_LOAN_WO_LOAN (LOAN_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='借款冲销明细（M8-8-3，FIFO 逐笔留痕）';

-- ---------- 6. 预提登记单（FR-4.6-8-1，决策⑦独立头表） ----------
CREATE TABLE IF NOT EXISTS erp_fin_prepaid_doc (
    ID VARCHAR(64) NOT NULL,
    PRE_NO VARCHAR(32) NOT NULL COMMENT '预提单号 PRE+yyyyMMdd+流水',
    EXPENSE_TYPE VARCHAR(32) COMMENT '费用类型（可空，直接用科目）',
    ACCOUNT_CODE VARCHAR(32) NOT NULL COMMENT '费用科目（计提 借方）',
    ACCOUNT_NAME VARCHAR(64),
    PERIOD VARCHAR(6) NOT NULL COMMENT '归属期间 YYYYMM（计提计划期间）',
    AMOUNT DECIMAL(18,2) NOT NULL COMMENT '预估金额',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'OPEN' COMMENT 'OPEN/SETTLED（SETTLED=已实际冲销）',
    ACTUAL_AMOUNT DECIMAL(18,2) DEFAULT NULL COMMENT '实际冲销金额（差异率基准）',
    SETTLE_DATE DATE,
    SETTLE_VOUCHER_ID VARCHAR(64) COMMENT '冲销凭证（借 2251 / 贷 1002 或应付；差异>0.5% 内生调整行）',
    SETTLE_REMARK VARCHAR(512),
    REMARK VARCHAR(255),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_PREPAID_NO (PRE_NO),
    KEY IDX_FIN_PREPAID_PERIOD (PERIOD, STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='预提费用登记单（M8-9-1，spec prepaid-amortization）';

-- ---------- 7. 待摊登记单（FR-4.6-8-1，BR-4.6-05 摊销月数） ----------
CREATE TABLE IF NOT EXISTS erp_fin_deferred_doc (
    ID VARCHAR(64) NOT NULL,
    DEF_NO VARCHAR(32) NOT NULL COMMENT '待摊单号 DEF+yyyyMMdd+流水',
    SUMMARY VARCHAR(255) COMMENT '事项说明（如：办公房租）',
    TOTAL_AMOUNT DECIMAL(18,2) NOT NULL COMMENT '总金额',
    AMORT_MONTHS INT NOT NULL COMMENT '摊销月数（>12 L4 提示转长期待摊）',
    START_PERIOD VARCHAR(6) NOT NULL COMMENT '起始期间 YYYYMM',
    EXPENSE_ACCOUNT_CODE VARCHAR(32) NOT NULL COMMENT '费用科目（摊销 借方）',
    EXPENSE_ACCOUNT_NAME VARCHAR(64),
    ASSET_ACCOUNT_CODE VARCHAR(32) NOT NULL DEFAULT '1801' COMMENT '待摊资产科目（登记时显式指定，design D7）',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'OPEN' COMMENT 'OPEN/COMPLETED（全部摊完）',
    REMARK VARCHAR(255),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_DEFERRED_NO (DEF_NO),
    KEY IDX_FIN_DEFERRED_PERIOD (START_PERIOD)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='待摊费用登记单（M8-9-2，spec prepaid-amortization）';

-- ---------- 8. 摊销/计提计划行（FR-4.6-8-2，决策⑦预提待摊共用；幂等锚 GEN_STATUS） ----------
CREATE TABLE IF NOT EXISTS erp_fin_amort_plan (
    ID VARCHAR(64) NOT NULL,
    PLAN_TYPE VARCHAR(8) NOT NULL COMMENT 'PREPAY 预提计提 / AMORT 待摊摊销',
    DOC_ID VARCHAR(64) NOT NULL COMMENT '登记单 ID',
    DOC_NO VARCHAR(32) NOT NULL COMMENT '登记单号',
    PERIOD VARCHAR(6) NOT NULL COMMENT '计划期间 YYYYMM',
    AMOUNT DECIMAL(18,2) NOT NULL COMMENT '计划金额（直线法，尾差并入末期）',
    GEN_STATUS VARCHAR(16) NOT NULL DEFAULT 'NOT_GEN' COMMENT 'NOT_GEN/GENERATED（结账⑨闸口与幂等锚，条件回写）',
    VOUCHER_ID VARCHAR(64) COMMENT '生成的 DRAFT 凭证 ID（FR-4.6-8-4 制单≠审核）',
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME,
    VER_NO INT DEFAULT 0,
    DEL_FLAG CHAR(1) DEFAULT '0',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_AMORT_PLAN_DOC_PERIOD (PLAN_TYPE, DOC_ID, PERIOD),
    KEY IDX_FIN_AMORT_PLAN_PERIOD (PERIOD, GEN_STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='预提/待摊计划行（M8-9，spec prepaid-amortization）';

