--     spec transfer-order / scrap-order / internal-transfer-accounting / outbound-workbench）
-- 幂等：CREATE IF NOT EXISTS / INSERT IGNORE / information_schema + PREPARE 动态 DDL（040/055/101/105 范式）

-- ---------- 1) erp_inv_warehouse 加 LE_CODE（跨法人判定唯一依据，design D4） ----------
SET @ddl = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE()
        AND TABLE_NAME = 'erp_inv_warehouse'
        AND COLUMN_NAME = 'LE_CODE') = 0,
    'ALTER TABLE erp_inv_warehouse
       ADD COLUMN LE_CODE VARCHAR(32) DEFAULT NULL
         COMMENT ''所属法人 LE_CODE（空按 LE-0001，跨法人调拨判定依据）'' AFTER ORG_UNIT',
    'SELECT 1');
