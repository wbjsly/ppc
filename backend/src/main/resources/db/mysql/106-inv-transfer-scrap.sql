-- ---------- 2) 调拨单头 ----------
CREATE TABLE IF NOT EXISTS erp_inv_transfer_order (
    ID VARCHAR(64) NOT NULL,
    TRANSFER_NO VARCHAR(32) NOT NULL COMMENT '调拨单号 TR+yyyyMMdd+流水',
    OUT_WH_CODE VARCHAR(32) NOT NULL COMMENT '调出仓',
    IN_WH_CODE VARCHAR(32) NOT NULL COMMENT '调入仓',
    OUT_LE_CODE VARCHAR(32) NOT NULL COMMENT '调出方法人（解析自调出仓 LE_CODE，空=LE-0001）',
    IN_LE_CODE VARCHAR(32) NOT NULL COMMENT '调入方法人',
    -- 1=跨法人（触发成对凭证/内部发票链），0=同法人移库（零凭证）
    CROSS_LE VARCHAR(1) NOT NULL DEFAULT '0' COMMENT '跨法人标记 1/0',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT→OUT_POSTED→IN_POSTED→CLOSED（+CANCELLED）',
    -- 超 TRANSIT_ALERT_DAYS 未入库由调度置 1（保留 OUT_POSTED 语义，C-4.4-09）
    SUSPENDED_FLAG VARCHAR(1) NOT NULL DEFAULT '0' COMMENT '在途超期挂起 1/0',
    OUT_POST_AT DATETIME DEFAULT NULL COMMENT '出库过账时间（在途起算）',
    IN_POST_AT DATETIME DEFAULT NULL COMMENT '入库过账时间',
    CLOSE_BY VARCHAR(64) DEFAULT NULL,
    CLOSE_AT DATETIME DEFAULT NULL,
    CANCEL_REASON VARCHAR(255) DEFAULT NULL,
    TOTAL_QTY DECIMAL(18,4) NOT NULL DEFAULT 0,
    TOTAL_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT 'Σ行金额（内部转移价×数量）',
    ALLOC_JSON TEXT COMMENT '出库过账分配结果 [{lineNo,itemCode,batchNo,binCode,qty}]（入库段按批入账依据）',
    REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_TR_NO (TRANSFER_NO),
    KEY IDX_TR_STATUS (STATUS, SUSPENDED_FLAG),
    KEY IDX_TR_OUTWH (OUT_WH_CODE, STATUS),
    KEY IDX_TR_INWH (IN_WH_CODE, STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='调拨单头（4.12.1/4.12.2/4.5.3/4.4.4 共享实体）';

-- ---------- 2b) erp_inv_transfer_order 加 ALLOC_JSON（首跑后补列场景，动态幂等） ----------
SET @ddl = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE()
        AND TABLE_NAME = 'erp_inv_transfer_order'
        AND COLUMN_NAME = 'ALLOC_JSON') = 0,
    'ALTER TABLE erp_inv_transfer_order
       ADD COLUMN ALLOC_JSON TEXT
         COMMENT ''出库过账分配结果（入库段按批入账依据）'' AFTER TOTAL_AMOUNT',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- ---------- 3) 调拨单行 ----------
CREATE TABLE IF NOT EXISTS erp_inv_transfer_order_line (
    ID VARCHAR(64) NOT NULL,
    ORDER_ID VARCHAR(64) NOT NULL,
    LINE_NO INT NOT NULL DEFAULT 1,
    ITEM_CODE VARCHAR(64) NOT NULL,
    ITEM_NAME VARCHAR(128) DEFAULT NULL,
    BATCH_NO VARCHAR(64) NOT NULL DEFAULT '' COMMENT '批次（空=过账时引擎 FIFO 分配）',
    QTY DECIMAL(18,4) NOT NULL COMMENT '调拨数量（>0）',
    -- 取价方案 a：单据行手工必填（>0），跨法人凭证/发票金额依据
    INTERNAL_PRICE DECIMAL(18,4) NOT NULL COMMENT '内部转移价（必填 >0）',
    LINE_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT 'QTY×INTERNAL_PRICE',
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_TRL_ORDER (ORDER_ID, LINE_NO),
    KEY IDX_TRL_ITEM (ITEM_CODE, BATCH_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='调拨单行（行级内部转移价）';

-- ---------- 4) 报废单头 ----------
CREATE TABLE IF NOT EXISTS erp_inv_scrap_order (
    ID VARCHAR(64) NOT NULL,
    SCRAP_NO VARCHAR(32) NOT NULL COMMENT '报废单号 SC+yyyyMMdd+流水',
    -- STALE 呆滞（三方会签 C-4.4-14）/ QUALITY 质量（挂 NCR）/ DAMAGE 损坏 / OTHER 其他（免会签，偏差 D1）
    REASON VARCHAR(16) NOT NULL COMMENT '报废原因 STALE/QUALITY/DAMAGE/OTHER',
    NCR_NO VARCHAR(64) DEFAULT NULL COMMENT 'NCR 关联号（QUALITY 必填）',
    WAREHOUSE_CODE VARCHAR(32) NOT NULL COMMENT '报废仓库',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT→APPROVED→POSTED→DISPOSED（+CANCELLED）',
    APPR_ID VARCHAR(64) DEFAULT NULL COMMENT '三方会签审批实例 ID（仅 STALE）',
    CANCEL_REASON VARCHAR(255) DEFAULT NULL,
    POST_BY VARCHAR(64) DEFAULT NULL,
    POST_AT DATETIME DEFAULT NULL,
    DISPOSE_BY VARCHAR(64) DEFAULT NULL COMMENT '处置核销人',
    DISPOSE_AT DATETIME DEFAULT NULL,
    TOTAL_QTY DECIMAL(18,4) NOT NULL DEFAULT 0,
    TOTAL_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '凭证金额合计（Σ行 QTY×UNIT_COST）',
    REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_SC_NO (SCRAP_NO),
    KEY IDX_SC_STATUS (STATUS, REASON),
    KEY IDX_SC_NCR (NCR_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='报废出库单（4.5.4，按原因分门槛）';

