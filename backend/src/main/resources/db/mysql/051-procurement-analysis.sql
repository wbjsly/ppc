-- ---------- 8) 记分卡结果（月度不可变 + 修正版多版本） ----------
CREATE TABLE IF NOT EXISTS erp_scm_scorecard_result (
    ID VARCHAR(64) NOT NULL,
    MONTH_TAG CHAR(6) NOT NULL COMMENT '评分周期（自然月）',
    SUPPLIER_ID VARCHAR(64) NOT NULL,
    MODEL_ID VARCHAR(64) NOT NULL,
    MODEL_VERSION INT NOT NULL DEFAULT 1 COMMENT '所用模型版本（可追溯）',
    Q_VALUE DECIMAL(8,2) DEFAULT NULL COMMENT '质量维度值（合格率%/PPM 等，穿透用）',
    Q_SCORE DECIMAL(6,2) DEFAULT NULL,
    D_VALUE DECIMAL(8,2) DEFAULT NULL COMMENT '交付维度值（准时率%）',
    D_SCORE DECIMAL(6,2) DEFAULT NULL,
    C_VALUE DECIMAL(8,2) DEFAULT NULL COMMENT '成本维度值（价格竞争力指数）',
    C_SCORE DECIMAL(6,2) DEFAULT NULL,
    R_VALUE DECIMAL(8,2) DEFAULT NULL COMMENT '响应维度值（PO 确认及时率%）',
    R_SCORE DECIMAL(6,2) DEFAULT NULL,
    TOTAL_SCORE DECIMAL(6,2) DEFAULT NULL,
    GRADE VARCHAR(4) DEFAULT NULL COMMENT 'A / B / C / D；异常时 NULL 不输出等级',
    DATA_STATUS VARCHAR(16) NOT NULL DEFAULT 'OK'
        COMMENT 'OK / MISSING_DIM 数据缺失 / INCOMPLETE 数据不完整暂缓发布 / ABNORMAL 计算异常转人工',
    VERSION_TAG VARCHAR(24) NOT NULL DEFAULT 'v1' COMMENT 'v1 / v2修正版…（申诉修正递增）',
    ORIGIN_ID VARCHAR(64) DEFAULT NULL COMMENT '修正版指向原结果 ID（原版保留备查）',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'GENERATED'
        COMMENT 'GENERATED / REVIEWED / PUBLISHED / SUSPENDED 暂缓',
    SOURCE_JSON TEXT COMMENT '采集明细（穿透查看数据来源）',
    CALC_AT DATETIME DEFAULT NULL,
    REVIEW_BY VARCHAR(64) DEFAULT NULL,
    REVIEW_AT DATETIME DEFAULT NULL,
    PUBLISH_AT DATETIME DEFAULT NULL,
    APPEAL_DEADLINE DATETIME DEFAULT NULL COMMENT '公示 +7 工作日',
    REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY uk_scorecard_ver (MONTH_TAG, SUPPLIER_ID, VERSION_TAG),
    KEY idx_scorecard_supp (SUPPLIER_ID, MONTH_TAG),
    KEY idx_scorecard_status (STATUS, MONTH_TAG)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='供应商绩效记分卡（采集不可手工修改，申诉出修正版新行）';

