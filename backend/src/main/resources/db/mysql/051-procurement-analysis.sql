    THRESH_A DECIMAL(5,2) NOT NULL DEFAULT 90.00,
    THRESH_B DECIMAL(5,2) NOT NULL DEFAULT 75.00,
    THRESH_C DECIMAL(5,2) NOT NULL DEFAULT 60.00,
    VERSION INT NOT NULL DEFAULT 1,
    STATUS VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT / ACTIVE / RETIRED',
    APPROVAL_STATUS VARCHAR(16) DEFAULT NULL COMMENT '变更审批 PENDING / APPROVED / REJECTED',
