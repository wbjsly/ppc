    PREV_PRICE DECIMAL(18,4) DEFAULT NULL,
    CURR_PRICE DECIMAL(18,4) DEFAULT NULL,
    SOURCE VARCHAR(16) NOT NULL DEFAULT 'EXTRACT' COMMENT 'EXTRACT 每日抽取 / MANUAL 实时补算',
