-- ---------- 1) 指标口径字典（design D4，七要素 + 行级版本单表） ----------
CREATE TABLE IF NOT EXISTS erp_bi_metric_dict (
    ID VARCHAR(64) NOT NULL,
    METRIC_KEY VARCHAR(64) NOT NULL COMMENT '指标唯一键（如 COST_PO_AMT）',
    NAME VARCHAR(128) NOT NULL COMMENT '指标名称',
    DEFINITION TEXT COMMENT '业务定义',
    FORMULA TEXT NOT NULL COMMENT '计算公式（JSON 结构化，diff 校验对象）',
    DATA_PRECISION INT NOT NULL DEFAULT 2 COMMENT '数据精度（小数位）',
    TIME_DIM VARCHAR(32) NOT NULL DEFAULT 'MONTH' COMMENT '时间维度 DAY/MONTH/QUARTER/YEAR',
    FILTER_COND VARCHAR(500) DEFAULT NULL COMMENT '过滤条件（JSON）',
    SRC_MAPPING TEXT COMMENT '来源字段映射（JSON：表.列 → 公式变量）',
    VERSION INT NOT NULL DEFAULT 1 COMMENT '版本号（同 METRIC_KEY 递增，行级历史）',
    IS_CURRENT TINYINT(1) NOT NULL DEFAULT 1 COMMENT '当前生效版本（历史行=0，design D4 回溯）',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'DRAFT'
        COMMENT 'DRAFT 草稿 / PUBLISHED 已发布 / PENDING_UPDATE 待更新',
    USED_BY TEXT COMMENT '引用方清单（JSON：能力标识列表，反向扫描对象）',
    REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY uk_bi_dict_key_ver (METRIC_KEY, VERSION),
    KEY idx_bi_dict_status (STATUS, IS_CURRENT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='指标口径字典（C-4.10-01 唯一权威，行级版本）';

-- ---------- 2) 抽取任务与批次（design D9，DAG + 水位 + READY） ----------
CREATE TABLE IF NOT EXISTS erp_bi_extract_task (
    ID VARCHAR(64) NOT NULL,
    BATCH_NO VARCHAR(32) NOT NULL COMMENT '批次号 yyyyMMdd-SEQ',
    BATCH_DATE DATE NOT NULL,
    TASK_TYPE VARCHAR(24) NOT NULL COMMENT 'PO / GR / AP / COST_SNAPSHOT / PRICE_ALERT / COST_SAVE',
    SEQ INT NOT NULL DEFAULT 10 COMMENT 'DAG 层序（同批次内上游 SEQ 小）',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        COMMENT 'PENDING / RUNNING / READY / PAUSED 波动暂停 / FAILED / SKIPPED',
    ROW_COUNT BIGINT NOT NULL DEFAULT 0,
    PREV_ROW_COUNT BIGINT DEFAULT NULL COMMENT '前一日行数（波动判定对照）',
    WATERMARK VARCHAR(64) DEFAULT NULL COMMENT '增量水位（最后处理位置，断点续抽）',
    RETRY INT NOT NULL DEFAULT 0,
    ERROR_MSG VARCHAR(500) DEFAULT NULL,
    MANUAL_CONFIRM TINYINT(1) NOT NULL DEFAULT 0 COMMENT '波动暂停后人工确认标记',
    FINISHED_AT DATETIME DEFAULT NULL,
    REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY uk_bi_extract_type (BATCH_DATE, TASK_TYPE),
    KEY idx_bi_extract_status (STATUS, SEQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='BI 抽取任务批次（依赖驱动 + 时间窗口）';

-- ---------- 3) 行列权限规则（design D6，查询层显式注入） ----------
CREATE TABLE IF NOT EXISTS erp_bi_perm_rule (
    ID VARCHAR(64) NOT NULL,
    RULE_TYPE VARCHAR(16) NOT NULL COMMENT 'ROW_LE 法人主体行级 / COL_MASK 列掩码 / COL_SENSITIVE 敏感登记',
    TARGET_KEY VARCHAR(128) NOT NULL COMMENT '对象（字段名 / 通配 *）',
    USER_NAME VARCHAR(64) DEFAULT NULL COMMENT '行级绑定用户（ROW_LE 必填）',
    ENTITY_ID VARCHAR(64) DEFAULT NULL COMMENT '允许访问的法人主体（ROW_LE）',
    ROLE_CODE VARCHAR(64) DEFAULT NULL COMMENT '适用角色（COL_* 时）',
    ACTION VARCHAR(16) NOT NULL DEFAULT 'PASS' COMMENT 'PASS / MASK / DENY',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'ENABLED',
    REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY idx_bi_perm_type (RULE_TYPE, STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='分析查询行列权限规则（C-4.10-02 执行依据）';

-- ---------- 4) 后台导出与查询审计一体（design D6：审计并入本表） ----------
CREATE TABLE IF NOT EXISTS erp_bi_export_task (
    ID VARCHAR(64) NOT NULL,
    TASK_TYPE VARCHAR(16) NOT NULL COMMENT 'QUERY 查询审计 / EXPORT 后台导出',
    TASK_NO VARCHAR(32) DEFAULT NULL COMMENT '导出任务号（QUERY 为空）',
    API_PATH VARCHAR(255) DEFAULT NULL,
    PARAMS_JSON TEXT COMMENT '参数摘要 / 过滤条件',
    MASK_COLS VARCHAR(500) DEFAULT NULL COMMENT '本次命中的掩码字段列表',
    USER_NAME VARCHAR(64) DEFAULT NULL,
    ROW_COUNT BIGINT DEFAULT NULL COMMENT '结果行数（导出完成后回填）',
    EST_ROWS BIGINT DEFAULT NULL COMMENT '预估行数（>EXPORT_ROW_LIMIT 转审批依据）',
    STATUS VARCHAR(16) NOT NULL DEFAULT 'DONE'
        COMMENT 'QUERY 恒 DONE；EXPORT：QUEUED / RUNNING / DONE / FAILED / REJECTED',
    APPROVAL_STATUS VARCHAR(16) DEFAULT NULL COMMENT '超量审批 PENDING / APPROVED / REJECTED（C-4.10-05）',
    FILE_PATH VARCHAR(255) DEFAULT NULL,
    WATERMARK VARCHAR(128) DEFAULT NULL COMMENT '用户名+时间戳+唯一流水号水印',
    REQ_ID VARCHAR(64) DEFAULT NULL COMMENT '请求标识（全链路）',
    NOTIFY TINYINT(1) NOT NULL DEFAULT 0 COMMENT '站内通知已发标记',
    EXPIRE_AT DATETIME DEFAULT NULL COMMENT '文件保留 7 天',
    ERROR_MSG VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY idx_bi_export_type (TASK_TYPE, CREATE_DATE),
    KEY idx_bi_export_user (USER_NAME, CREATE_DATE),
    KEY idx_bi_export_status (STATUS, TASK_TYPE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='后台导出任务与查询审计（≥365 天，design D6 合表）';

-- ---------- 5) 成本快照（design D2：单快照行双金额列） ----------
CREATE TABLE IF NOT EXISTS erp_bi_cost_snapshot (
    ID VARCHAR(64) NOT NULL,
    BATCH_NO VARCHAR(32) DEFAULT NULL COMMENT '生成批次（READY 前置）',
    MONTH_TAG CHAR(6) NOT NULL COMMENT 'yyyyMM 归属月',
    LEGAL_ENTITY_ID VARCHAR(64) NOT NULL DEFAULT 'LE-DEFAULT',
    CATEGORY_CODE VARCHAR(64) DEFAULT NULL COMMENT '品类（趋势同品类分位用）',
    ITEM_CODE VARCHAR(64) NOT NULL,
    SUPPLIER_ID VARCHAR(64) NOT NULL,
    BUYER VARCHAR(64) DEFAULT NULL COMMENT '采购员（降本三维之一）',
    PO_QTY DECIMAL(18,4) NOT NULL DEFAULT 0,
    PO_AMT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT 'PO 承诺成本（含税）',
    PO_AMT_NO_TAX DECIMAL(18,2) NOT NULL DEFAULT 0,
    TAX_AMT DECIMAL(18,2) NOT NULL DEFAULT 0,
    FREIGHT_AMT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '运费单列',
    RETURN_AMT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '退货红字冲减（正数表示扣减）',
    INV_QTY DECIMAL(18,4) DEFAULT NULL,
    INV_AMT DECIMAL(18,2) DEFAULT NULL COMMENT '发票实付（含税）；NULL=未开票',
    INV_AMT_NO_TAX DECIMAL(18,2) DEFAULT NULL,
    INV_TAX DECIMAL(18,2) DEFAULT NULL,
    DIFF_AMT DECIMAL(18,2) DEFAULT NULL COMMENT '差异 = INV_AMT - PO_AMT',
    ESTIMATING TINYINT(1) NOT NULL DEFAULT 0 COMMENT '1=暂估中（发票口径为空不冒充实付）',
    REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY uk_bi_snap_dim (MONTH_TAG, LEGAL_ENTITY_ID, ITEM_CODE, SUPPLIER_ID),
    KEY idx_bi_snap_item (ITEM_CODE, MONTH_TAG),
    KEY idx_bi_snap_supp (SUPPLIER_ID, MONTH_TAG),
    KEY idx_bi_snap_buyer (BUYER, MONTH_TAG)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='采购成本日聚合快照（双口径并列，design D2）';

-- ---------- 6) 价格异动台账（spec procurement-cost-analysis 幂等 + 状态机） ----------
