-- ---------- 4. 转资单（FR-4.13-1-2~6 载体） ----------
CREATE TABLE IF NOT EXISTS erp_eam_capitalization (
    ID VARCHAR(64) NOT NULL,
    -- ZT + yyyyMMdd + - + 4 位流水
    CAP_NO VARCHAR(32) NOT NULL,
    -- PURCHASE 采购转资 / CIP 在建转资
    MODE VARCHAR(16) NOT NULL,
    -- 来源：采购订单 ID / CIP 项目 ID
    SOURCE_ID VARCHAR(64) NOT NULL,
    SOURCE_DOC_NO VARCHAR(64),
    ASSET_NAME VARCHAR(255) NOT NULL,
    SPEC_MODEL VARCHAR(255),
    -- 一物一卡拆分数量（D3，上限 500）
    QTY INT NOT NULL DEFAULT 1,
    CATEGORY_CODE VARCHAR(32) NOT NULL,
    DEPT_NAME VARCHAR(128),
    COST_CENTER_CODE VARCHAR(32),
    STORAGE_LOCATION VARCHAR(128),
    -- 原值合计（单件原值 × 数量）
    TOTAL_AMOUNT DECIMAL(18,2) NOT NULL,
    UNIT_AMOUNT DECIMAL(18,2) NOT NULL,
    -- 折旧政策（录入值；建卡时快照到卡）
    LIFE_YEARS INT NOT NULL,
    RESIDUAL_RATE DECIMAL(5,4) NOT NULL,
    DEPRECIATION_METHOD VARCHAR(16) NOT NULL DEFAULT 'STRAIGHT_LINE',
    -- 启用日期（BR-4.13-06 = 验收合格日）
    EFFECTIVE_DATE DATE NOT NULL,
    -- 部分转资（BR-4.13-08）
    PARTIAL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    PARTIAL_REMARK VARCHAR(500),
    -- ADJUST 原值/年限调整原因（FR-4.13-1-3 可调需说明）
    ADJUST_REASON VARCHAR(500),
    -- DRAFT / PENDING_APPROVE / APPROVED / REJECTED / COMPLETED
    STATUS VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    APPROVAL_ID VARCHAR(64),
    REJECT_REASON VARCHAR(500),
    VOUCHER_ID VARCHAR(64),
    CARD_COUNT INT,
    REMARK VARCHAR(500),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_EAM_CAP_NO (CAP_NO),
    KEY IDX_EAM_CAP_STATUS (STATUS),
    KEY IDX_EAM_CAP_SOURCE (SOURCE_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- ---------- 5. 资产卡片（一物一卡；BR-4.13-10 锁定；为 7.2 折旧铺五字段） ----------
CREATE TABLE IF NOT EXISTS erp_eam_asset_card (
    ID VARCHAR(64) NOT NULL,
    -- ZC + yyyyMMdd + 4 位流水（系统生成不可改）
    CARD_NO VARCHAR(32) NOT NULL,
    ASSET_NAME VARCHAR(255) NOT NULL,
    SPEC_MODEL VARCHAR(255),
    CATEGORY_CODE VARCHAR(32) NOT NULL,
    DEPT_NAME VARCHAR(128),
    COST_CENTER_CODE VARCHAR(32),
    STORAGE_LOCATION VARCHAR(128),
    -- 折旧政策五字段（BR-4.13-10 锁定对象）
    ASSET_COST DECIMAL(18,2) NOT NULL,
    LIFE_YEARS INT NOT NULL,
    RESIDUAL_RATE DECIMAL(5,4) NOT NULL,
    DEPRECIATION_METHOD VARCHAR(16) NOT NULL DEFAULT 'STRAIGHT_LINE',
    EFFECTIVE_DATE DATE NOT NULL,
    -- 在用 / 已处置（本变更仅建「在用」）
    STATUS VARCHAR(16) NOT NULL DEFAULT 'IN_USE',
    -- NOT_DEPRECIATED / DEPRECIATING / FULLY_DEPRECIATED（7.2 取用）
    DEPR_STATUS VARCHAR(24) NOT NULL DEFAULT 'NOT_DEPRECIATED',
    ACCUM_DEPR DECIMAL(18,2) NOT NULL DEFAULT 0,
    -- 凭证过账后锁定标志（BR-4.13-10）
    LOCK_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    SOURCE_CAP_ID VARCHAR(64),
    SOURCE_CAP_NO VARCHAR(32),
    REMARK VARCHAR(500),
    CREATE_BY VARCHAR(64),
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64),
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_EAM_CARD_NO (CARD_NO),
    KEY IDX_EAM_CARD_STATUS (STATUS),
    KEY IDX_EAM_CARD_CAT (CATEGORY_CODE),
    KEY IDX_EAM_CARD_CAP (SOURCE_CAP_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
