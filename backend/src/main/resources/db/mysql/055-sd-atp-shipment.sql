-- ---------- 4) 销售发货（tasks 9.1，spec sales-shipment，D8 只做销售侧策略与确认） ----------

CREATE TABLE IF NOT EXISTS erp_sd_shipment (
    ID VARCHAR(64) NOT NULL,
    -- SH + yyyyMMdd + 4 位流水
    SHIP_NO VARCHAR(32) NOT NULL COMMENT '发货单号',
    -- PARTIAL 部分 / MERGE 合并 / BATCH 分批 / EXCHANGE 换货（12.6 复用）
    SHIP_TYPE VARCHAR(16) NOT NULL COMMENT 'PARTIAL/MERGE/BATCH/EXCHANGE',
    CUSTOMER_ID VARCHAR(64) NOT NULL,
    CUSTOMER_CODE VARCHAR(32) DEFAULT NULL,
    CUSTOMER_NAME VARCHAR(128) DEFAULT NULL,
    WAREHOUSE_CODE VARCHAR(32) NOT NULL DEFAULT 'WH-MAIN',
    -- DRAFT 草稿 / POSTED 已出库过账 / CONFIRMED 已发货确认 / SIGNED 已签收 / REJECTED 拒收 / CANCELLED
    STATUS VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT/POSTED/CONFIRMED/SIGNED/REJECTED/CANCELLED',
    TOTAL_QTY DECIMAL(18,3) NOT NULL DEFAULT 0,
    TOTAL_AMT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '应收事件金额 = Σ 行数量×单价',
    -- 9.7 物流信息
    LOGISTICS_CO VARCHAR(64) DEFAULT NULL COMMENT '物流公司',
    LOGISTICS_NO VARCHAR(64) DEFAULT NULL COMMENT '物流单号',
    SHIP_AT DATETIME DEFAULT NULL COMMENT '发货确认时间',
    -- 9.8 签收
    SIGN_DUE_DATE DATE DEFAULT NULL COMMENT '签收时限（确认日 + SIGN_TIMEOUT_DAYS）',
    SIGN_AT DATETIME DEFAULT NULL COMMENT '签收时间',
    SIGN_WARNED VARCHAR(1) NOT NULL DEFAULT '0' COMMENT '1 = 超时未签收已预警',
    -- 9.7 物流异常（记录并通知销售）
    EXCEPT_NOTE VARCHAR(500) DEFAULT NULL COMMENT '物流异常信息',
    EXCEPT_NOTIFY_AT DATETIME DEFAULT NULL,
    -- 9.8 拒收
    REJECT_REASON VARCHAR(500) DEFAULT NULL,
    REJECTED_AT DATETIME DEFAULT NULL,
    RETURN_ID VARCHAR(64) DEFAULT NULL COMMENT '拒收生成的退货申请 ID（12 组）',
    POST_BY VARCHAR(64) DEFAULT NULL,
    POST_AT DATETIME DEFAULT NULL COMMENT '出库过账时间',
    CONFIRM_BY VARCHAR(64) DEFAULT NULL,
    CONFIRM_AT DATETIME DEFAULT NULL,
    REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_SD_SHIP_NO (SHIP_NO),
    KEY IDX_SD_SHIP_CUST (CUSTOMER_ID, STATUS),
    KEY IDX_SD_SHIP_WH (WAREHOUSE_CODE, STATUS),
    KEY IDX_SD_SHIP_STATUS (STATUS, CREATE_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='销售发货单（3.7 部分/合并/分批策略与确认）';

CREATE TABLE IF NOT EXISTS erp_sd_shipment_line (
    ID VARCHAR(64) NOT NULL,
    SHIP_ID VARCHAR(64) NOT NULL,
    LINE_NO INT NOT NULL,
    -- 来源引用（合并发货保留多 SO 行级引用，spec 场景「多单合并」）
    SO_ID VARCHAR(64) NOT NULL,
    SO_NO VARCHAR(32) DEFAULT NULL,
    SO_LINE_ID VARCHAR(64) NOT NULL,
    SO_LINE_NO INT DEFAULT NULL,
    ITEM_CODE VARCHAR(64) NOT NULL,
    ITEM_NAME VARCHAR(255) DEFAULT NULL,
    QTY DECIMAL(18,3) NOT NULL COMMENT '发货数量（≤ 未发余量与可锁预留量，9.5）',
    BASE_UNIT VARCHAR(16) DEFAULT NULL,
    UNIT_PRICE DECIMAL(18,4) DEFAULT NULL COMMENT '来自 SO 行（应收事件金额口径）',
    AMOUNT DECIMAL(18,2) DEFAULT NULL,
    WAREHOUSE_CODE VARCHAR(32) NOT NULL DEFAULT 'WH-MAIN',
    PLAN_SHIP_DATE DATE DEFAULT NULL COMMENT '分批交期（9.4 行级带出）',
    -- PENDING 待过账 / POSTED 已过账 / CANCELLED
    LINE_STATUS VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    -- 过账 FIFO 选批结果 [{batchNo, qty}]（9.6 回填）
    BATCH_ALLOC JSON DEFAULT NULL,
    POST_AT DATETIME DEFAULT NULL,
    REMARK VARCHAR(500) DEFAULT NULL,
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_SD_SHIPLINE_SHIP (SHIP_ID, LINE_NO),
    KEY IDX_SD_SHIPLINE_SO (SO_ID, SO_LINE_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='销售发货单行（来源 SO 行引用与选批结果）';

