-- ---------- 2) erp_inv_stock 增加仓库维度：加列（NOT NULL DEFAULT 即完成存量回填） ----------
SET @ddl = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE()
        AND TABLE_NAME = 'erp_inv_stock'
        AND COLUMN_NAME = 'WAREHOUSE_CODE') = 0,
    'ALTER TABLE erp_inv_stock
       ADD COLUMN WAREHOUSE_CODE VARCHAR(32) NOT NULL DEFAULT ''WH-MAIN''
         COMMENT ''仓库编码（design D16，ATP 与发货按 SKU+仓库维度）'' AFTER ID',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- 存量回填（加列时已按默认值填充；此处兜底清理空串）
UPDATE erp_inv_stock SET WAREHOUSE_CODE = 'WH-MAIN'
 WHERE WAREHOUSE_CODE IS NULL OR WAREHOUSE_CODE = '';

-- ---------- 3) 唯一键升级：(ITEM_CODE, BATCH_NO) → (WAREHOUSE_CODE, ITEM_CODE, BATCH_NO) ----------
-- 先删旧唯一键（存在才删），再建新唯一键（不存在才建）；两步均幂等
SET @ddl = IF(
    (SELECT COUNT(*) FROM information_schema.STATISTICS
      WHERE TABLE_SCHEMA = DATABASE()
        AND TABLE_NAME = 'erp_inv_stock'
        AND INDEX_NAME = 'UK_STOCK_ITEM_BATCH') > 0,
    'ALTER TABLE erp_inv_stock DROP INDEX UK_STOCK_ITEM_BATCH',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

SET @ddl = IF(
    (SELECT COUNT(DISTINCT INDEX_NAME) FROM information_schema.STATISTICS
      WHERE TABLE_SCHEMA = DATABASE()
        AND TABLE_NAME = 'erp_inv_stock'
        AND INDEX_NAME = 'UK_STOCK_WH_ITEM_BATCH') = 0,
    'ALTER TABLE erp_inv_stock
       ADD UNIQUE KEY UK_STOCK_WH_ITEM_BATCH (WAREHOUSE_CODE, ITEM_CODE, BATCH_NO)',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

