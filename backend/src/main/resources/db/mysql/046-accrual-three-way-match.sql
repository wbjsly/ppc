    AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '行金额',
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    KEY IDX_FIN_INV_LINE_INV (INVOICE_ID),
    KEY IDX_FIN_INV_LINE_PO (PO_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- ---------- 7) 匹配结果 / 异常对账单 ----------
CREATE TABLE IF NOT EXISTS erp_fin_match_result (
    ID VARCHAR(64) NOT NULL,
    MATCH_NO VARCHAR(32) NOT NULL COMMENT '匹配单号 MT+yyyyMMdd+流水',
    INVOICE_ID VARCHAR(64) NOT NULL,
    INVOICE_NO VARCHAR(64) DEFAULT NULL,
    PO_NO VARCHAR(32) DEFAULT NULL,
    SUPPLIER_ID VARCHAR(64) DEFAULT NULL,
    SUPPLIER_NAME VARCHAR(128) DEFAULT NULL,
    STATUS VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        COMMENT 'MATCHED 匹配通过（已自动冲回）/ EXCEPTION 异常冻结待确认 / CONFIRMED 已确认待过账 / POSTED 已过账 / FAILED 匹配失败',
    DIFF_QTY_RATE DECIMAL(10,6) DEFAULT NULL COMMENT '数量差异率最大值',
    DIFF_PRICE_RATE DECIMAL(10,6) DEFAULT NULL COMMENT '单价差异率最大值',
    DIFF_AMOUNT DECIMAL(18,2) DEFAULT NULL COMMENT '金额差（发票额 − 暂估额）',
    DIFF_AMOUNT_RATE DECIMAL(10,6) DEFAULT NULL COMMENT '金额差异率',
    DETAIL TEXT COMMENT '逐行差异明细（JSON）',
    EXCEPTION_TYPE VARCHAR(32) DEFAULT NULL COMMENT 'PRICE_DIFF 价差超容差 / QTY_DIFF 数量不符 / NO_RECEIPT 无收货',
    PERIOD_CROSS TINYINT NOT NULL DEFAULT 0 COMMENT '跨会计期间（发票自然月 < 当前自然月，design D8）',
    CONFIRM_OPINION VARCHAR(255) DEFAULT NULL COMMENT '采购员价差确认意见',
    CONFIRM_BY VARCHAR(64) DEFAULT NULL,
    CONFIRM_AT DATETIME DEFAULT NULL,
    POST_BY VARCHAR(64) DEFAULT NULL,
    POST_AT DATETIME DEFAULT NULL,
    VOUCHER_ID VARCHAR(64) DEFAULT NULL COMMENT '正式应付/价差调整凭证 ID',
    ACCRUAL_BATCH_REVERSED TINYINT NOT NULL DEFAULT 0 COMMENT '是否已执行暂估自动冲回',
    CREATE_BY VARCHAR(64) DEFAULT NULL,
    CREATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT NULL,
    UPDATE_DATE DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DEL_FLAG VARCHAR(1) NOT NULL DEFAULT '0',
    VER_NO INT NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIN_MATCH_NO (MATCH_NO),
    KEY IDX_FIN_MATCH_INV (INVOICE_ID),
    KEY IDX_FIN_MATCH_STATUS (STATUS),
    KEY IDX_FIN_MATCH_SUP (SUPPLIER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

